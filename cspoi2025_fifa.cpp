const int maxn = 200000 + 5;
const int LOG = 20;

int n, m;
vector<int> adj[maxn];
int par[maxn];
int jump[maxn][LOG];
int tin[maxn], tout[maxn];
int h[maxn];
int timer_ent = 1;

void dfs(int u, int p) {
    par[u] = p;
    tin[u] = timer_ent++;
    for (int v : adj[u]) {
        if (v == p) continue;
        h[v] = h[u] + 1;
        dfs(v, u);
    }
    tout[u] = timer_ent - 1;
}

bool is_ancestor(int a, int b) {
    return tin[a] <= tin[b] && tout[b] <= tout[a];
}

int lca(int u, int v) {
    if (is_ancestor(u, v)) return u;
    if (is_ancestor(v, u)) return v;
    for (int j = LOG - 1; j >= 0; --j) {
        int up = jump[u][j];
        if (up != 0 && !is_ancestor(up, v))
            u = up;
    }
    return jump[u][0];
}

bool cmpvert(int u, int v) {
    return tie(tin[u], u) < tie(tin[v], v);
}

vector<vector<int>> virtualize(vector<int> verts, vector<int> &nodes_out) {
    vector<vector<int>> empty_vt(n + 1);
    if (verts.empty()) {
        nodes_out.clear();
        return empty_vt;
    }

    sort(verts.begin(), verts.end(), cmpvert);

    vector<int> nodes = verts;
    for (size_t i = 0; i + 1 < verts.size(); ++i) {
        nodes.push_back(lca(verts[i], verts[i + 1]));
    }

    sort(nodes.begin(), nodes.end(), cmpvert);
    nodes.erase(unique(nodes.begin(), nodes.end()), nodes.end());

    vector<vector<int>> vt(n + 1);
    stack<int> st;
    st.push(nodes[0]);

    for (size_t i = 1; i < nodes.size(); ++i) {
        int cur = nodes[i];
        while (!st.empty() && !is_ancestor(st.top(), cur)) st.pop();
        if (st.empty()) {
            st.push(cur);
            continue;
        }
        int parent = st.top();
        vt[parent].push_back(cur);
        st.push(cur);
    }

    nodes_out = std::move(nodes);
    return vt;
}

void prep() {
    timer_ent = 1;
    h[1] = 0;
    dfs(1, 0);

    for (int i = 1; i <= n; ++i) jump[i][0] = par[i];
    for (int j = 1; j < LOG; ++j) {
        for (int i = 1; i <= n; ++i) {
            int mid = jump[i][j - 1];
            jump[i][j] = mid ? jump[mid][j - 1] : 0;
        }
    }
}

long long find_farthest(int start, const vector<int> &verts, const vector<vector<pair<int,int>>> &g, int &farthest_node) {
    unordered_map<int,long long> dist;
    stack<pair<int,int>> st;
    st.push({start, 0});
    dist[start] = 0;

    while (!st.empty()) {
        auto [u, p] = st.top(); st.pop();
        for (auto &pr : g.at(u)) {
            int v = pr.first;
            int w = pr.second;
            if (v == p) continue;
            dist[v] = dist[u] + w;
            st.push({v, u});
        }
    }

    long long far_dist = -1;
    farthest_node = start;
    for (int s : verts) {
        auto it = dist.find(s);
        long long d = (it == dist.end() ? 0LL : it->second);
        if (d > far_dist) {
            far_dist = d;
            farthest_node = s;
        }
    }
    return far_dist;
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    cin >> n >> m;
    for (int i = 1; i <= n; ++i) adj[i].clear();

    vector<int> a(n + 1);
    for (int i = 1; i <= n; ++i) cin >> a[i];

    for (int i = 0; i < n - 1; ++i) {
        int u, v;
        cin >> u >> v;
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    prep();

    vector<vector<int>> by_val(m + 1);
    for (int i = 1; i <= n; ++i) {
        if (a[i] <= m) by_val[a[i]].push_back(i);
    }

    vector<long long> ans(m + 1, 0);

    for (int x = 1; x <= m; ++x) {
        vector<int> verts;
        for (int mult = x; mult <= m; mult += x) {
            for (int node : by_val[mult]) verts.push_back(node);
        }

        if (verts.empty() || verts.size() == 1) {
            ans[x] = 0;
            continue;
        }

        vector<int> nodes;
        vector<vector<int>> vt = virtualize(verts, nodes);

        vector<vector<pair<int, int>>> g(n + 1);
        long long edsum = 0;
        for (int u : nodes) {
            for (int v : vt[u]) {
                int w = h[v] - h[u];
                edsum += w;
                g[u].push_back({v, w});
                g[v].push_back({u, w});
            }
        }

        int far1, far2;
        find_farthest(verts[0], verts, g, far1);
        long long diameter = find_farthest(far1, verts, g, far2);

        ans[x] = 2 * edsum - diameter;
    }

    for (int x = 1; x <= m; ++x) {
        cout << ans[x] << "\n";
    }
}
