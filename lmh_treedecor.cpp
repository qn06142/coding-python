const int MAXC = 100000; 

struct Fenwick {
    int n;
    vector<long long> bit;
    Fenwick(int n=0){ init(n); }
    void init(int n_){ n = n_; bit.assign(n+1, 0); }
    void add(int idx, long long val){
        for(; idx <= n; idx += idx & -idx) bit[idx] += val;
    }
    long long sumPrefix(int idx){
        long long s = 0;
        for(; idx > 0; idx -= idx & -idx) s += bit[idx];
        return s;
    }
};

struct Fenwick1 {
    int n;
    Fenwick B1, B2;
    Fenwick1(int n=0){ init(n); }
    void init(int n_){
        n = n_;
        B1.init(n);
        B2.init(n);
    }

    void range_add(int l, int r, long long v){
        if(l > r) return;
        B1.add(l, v);
        B1.add(r+1, -v);
        B2.add(l, v*(l-1));
        B2.add(r+1, -v*r);
    }

    long long prefix_sum(int x){
        return B1.sumPrefix(x)*x - B2.sumPrefix(x);
    }

    long long range_sum(int l, int r){
        if(l > r) return 0;
        return prefix_sum(r) - prefix_sum(l-1);
    }
};

int n, q;
vector<vector<int>> g;
vector<int> tin, tout;
int timerdfs = 0;

void dfs(int root=1){

    vector<int> st; st.reserve(n);
    vector<int> it(n+1, 0);
    st.push_back(root);
    int parent = 0;
    vector<int> parentv(n+1, 0);
    while(!st.empty()){
        int v = st.back();
        if(it[v] == 0){
            tin[v] = ++timerdfs;
        }
        if(it[v] < (int)g[v].size()){
            int to = g[v][it[v]++];
            if(to == parentv[v]) continue;
            parentv[to] = v;
            st.push_back(to);
        } else {
            tout[v] = timerdfs;
            st.pop_back();
        }
    }
}

