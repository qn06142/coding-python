const int maxn = 3e5 + 5;

long long h[maxn], dp[maxn];
long long t[4 * maxn], lz[4 * maxn];
int mx[maxn], mn[maxn];
int mxtop = 0, mntop = 0;

void push(int u) {
    if (lz[u]) {
        long long v = lz[u];

        if (t[u * 2] < 1000000000000000000LL / 2) {
            t[u * 2] += v;
        }
        lz[u * 2] += v;

        if (t[u * 2 + 1] < 1000000000000000000LL / 2) {
            t[u * 2 + 1] += v;
        }
        lz[u * 2 + 1] += v;

        lz[u] = 0;
    }
}

void upd(int u, int l, int r, int p, long long v) {
    if (l == r) {
        t[u] = v;
        lz[u] = 0;
        return;
    }

    push(u);
    int mid = (l + r) / 2;

    if (p <= mid) {
        upd(u * 2, l, mid, p, v);
    } else {
        upd(u * 2 + 1, mid + 1, r, p, v);
    }

    t[u] = min(t[u * 2], t[u * 2 + 1]);
}

void add(int u, int l, int r, int ql, int qr, long long v) {
    if (ql > r || qr < l) {
        return;
    }

    if (ql <= l && r <= qr) {
        if (t[u] < 1000000000000000000LL / 2) {
            t[u] += v;
        }

        lz[u] += v;
        return;
    }

    push(u);
    int mid = (l + r) / 2;

    add(u * 2, l, mid, ql, qr, v);
    add(u * 2 + 1, mid + 1, r, ql, qr, v);

    t[u] = min(t[u * 2], t[u * 2 + 1]);
}

long long qry(int u, int l, int r, int ql, int qr) {
    if (ql > r || qr < l) {
        return 1000000000000000000LL;
    }

    if (ql <= l && r <= qr) {
        return t[u];
    }

    push(u);
    int mid = (l + r) / 2;

    return min(qry(u * 2, l, mid, ql, qr),
               qry(u * 2 + 1, mid + 1, r, ql, qr));
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(0);

    int n, k, m;
    cin >> n >> k >> m;

    for (int i = 1; i <= n; i++) {
        cin >> h[i];
    }

    fill(t, t + 4 * (n + 2), 1000000000000000000LL);
    fill(lz, lz + 4 * (n + 2), 0);

    dp[1] = 0;
    upd(1, 1, n + 1, 1, 0);

    debug(n, k, m);

    for (int i = 1; i <= n; i++) {
        while (mxtop && h[mx[mxtop]] <= h[i]) {
            int j = mx[mxtop--];
            int p = mxtop ? mx[mxtop] : 0;

            add(1, 1, n + 1, p + 1, j, h[i] - h[j]);
        }

        mx[++mxtop] = i;

        while (mntop && h[mn[mntop]] >= h[i]) {
            int j = mn[mntop--];
            int p = mntop ? mn[mntop] : 0;

            add(1, 1, n + 1, p + 1, j, h[j] - h[i]);
        }

        mn[++mntop] = i;

        if (i >= k) {
            int l = max(0, i - m);
            int r = i - k;
            long long best = qry(1, 1, n + 1, l + 1, r + 1);

            if (best < 1000000000000000000LL / 2) {
                dp[i + 1] = best;
                upd(1, 1, n + 1, i + 1, dp[i + 1]);
            }

            if (i <= 3 || i == n) {
                debug(i, l, r, best, dp[i + 1]);
            }
        }
    }

    debug(dp[n + 1]);

    cout << (dp[n + 1] >= 1000000000000000000LL / 2 ? -1 : dp[n + 1]) << '\n';
}