int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int n, m;
    cin >> n >> m;

    vector<int> raw_col(n+1);
    for (int i = 1; i <= n; ++i) cin >> raw_col[i];

    vector<vector<int>> g(n+1);
    for (int i = 0; i < n-1; ++i) {
        int u, v; cin >> u >> v;
        g[u].push_back(v);
        g[v].push_back(u);
    }

    unordered_map<int,int> comp;
    comp.reserve(n*2);
    vector<int> rev;
    for (int i = 1; i <= n; ++i) {
        int x = raw_col[i];
        if (!comp.count(x)) {
            comp[x] = (int)rev.size();
            rev.push_back(x);
        }
    }
    int C = rev.size();
    vector<int> col(n+1);
    for (int i = 1; i <= n; ++i) col[i] = comp[raw_col[i]];

    int B = max(1, (int)ceil(sqrt((double)n)));
    vector<int> freq(C,0);
    for (int i = 1; i <= n; ++i) ++freq[col[i]];
    vector<int> heavy_; heavy_.reserve(C);
    vector<int> heavy_id(C, -1);
    for (int c = 0; c < C; ++c) if (freq[c] > B) {
        heavy_id[c] = (int)heavy_.size();
        heavy_.push_back(c);
    }
    int H = heavy_.size();

    int LOG = 1; while ((1<<LOG) <= n) ++LOG;
    vector<vector<int>> parent(LOG, vector<int>(n+1, 0));
    vector<int> depth(n+1,0), sz(n+1,0);
    vector<vector<int>> children(n+1);
    vector<int> st; st.reserve(n);
    vector<int> it_idx(n+1,0), vis(n+1,0), order; order.reserve(n);

    st.push_back(1); vis[1]=1; parent[0][1]=0; depth[1]=0;
    while (!st.empty()) {
        int u = st.back();
        if (it_idx[u] == 0) order.push_back(u);
        if (it_idx[u] < (int)g[u].size()) {
            int v = g[u][it_idx[u]++];
            if (vis[v]) continue;
            vis[v] = 1;
            parent[0][v] = u;
            depth[v] = depth[u] + 1;
            children[u].push_back(v);
            st.push_back(v);
        } else st.pop_back();
    }
    for (int i = (int)order.size()-1; i >= 0; --i) {
        int u = order[i];
        sz[u] = 1;
        for (int v: children[u]) sz[u] += sz[v];
    }
    for (int k = 1; k < LOG; ++k)
        for (int v = 1; v <= n; ++v)
            parent[k][v] = parent[k-1][v] ? parent[k-1][ parent[k-1][v] ] : 0;

    auto lca = [&](int u, int v) {
        if (depth[u] < depth[v]) swap(u,v);
        int diff = depth[u] - depth[v];
        for (int k = 0; k < LOG; ++k) if (diff & (1<<k)) u = parent[k][u];
        if (u == v) return u;
        for (int k = LOG-1; k >= 0; --k) {
            if (parent[k][u] != parent[k][v]) { u = parent[k][u]; v = parent[k][v]; }
        }
        return parent[0][u];
    };

    vector<vector<int>> sub_heavy(H, vector<int>(n+1, 0));
    vector<vector<int>> up_heavy(H, vector<int>(n+1, 0));
    vector<int> total_heavy(H,0);

    for (int hid = 0; hid < H; ++hid) {
        int c = heavy_[hid];
        vector<pair<int,int>> stk; stk.reserve(n*2);
        stk.emplace_back(1,0);
        while (!stk.empty()) {
            auto [u, state] = stk.back(); stk.pop_back();
            if (state == 0) {
                up_heavy[hid][u] = parent[0][u] ? up_heavy[hid][ parent[0][u] ] + (col[u]==c) : (col[u]==c);
                stk.emplace_back(u,1);
                for (int v: children[u]) stk.emplace_back(v,0);
            } else {
                int s = (col[u]==c);
                for (int v: children[u]) s += sub_heavy[hid][v];
                sub_heavy[hid][u] = s;
            }
        }
        total_heavy[hid] = up_heavy[hid][ order.back() ];
    }

    vector<int> tmp; tmp.reserve(2*B + 5);
    auto subtree = [&](int u, vector<int>& out) {
        out.clear(); out.reserve(sz[u]);
        vector<int> stk2; stk2.push_back(u);
        while (!stk2.empty()) {
            int x = stk2.back(); stk2.pop_back();
            out.push_back(x);
            for (int v: children[x]) stk2.push_back(v);
        }
    };
    auto outtre = [&](int u, vector<int>& out) {
        out.clear(); out.reserve(max(0, n - sz[u]));
        if (n - sz[u] == 0) return;
        vector<int> stk2; stk2.push_back(1);
        while (!stk2.empty()) {
            int x = stk2.back(); stk2.pop_back();
            if (x == u) continue;
            out.push_back(x);
            for (int v: children[x]) if (v != u) stk2.push_back(v);
        }
    };
    auto enum_path = [&](int u, int v, vector<int>& out) {
        out.clear();
        int L = lca(u,v);
        vector<int> left, right;
        int x = u;
        while (x != L) { left.push_back(x); x = parent[0][x]; }
        left.push_back(L);
        x = v;
        while (x != L) { right.push_back(x); x = parent[0][x]; }
        out = left;
        for (int i = (int)right.size()-1; i >= 0; --i) out.push_back(right[i]);
    };

    unordered_map<int,int> cnt; cnt.reserve(4096);
    auto procbig = [&](const vector<int>& nodes) -> int {
        cnt.clear();
        int len = nodes.size();
        for (int u : nodes) {
            int c = col[u];
            int v = ++cnt[c];
            if (v * 2 > len) return c;
        }
        return -1;
    };

    for (int qi = 0; qi < m; ++qi) {
        int t; cin >> t;
        if (t == 1) {
            int u; cin >> u;
            int len = sz[u];
            if (len <= 2*B) {
                subtree(u, tmp);
                int cc = procbig(tmp);
                cout << (cc == -1 ? -1 : rev[cc]) << '\n';
            } else {
                int found = -1;
                for (int hid = 0; hid < H; ++hid) {
                    int cntc = sub_heavy[hid][u];
                    if (cntc * 2 > len) { found = heavy_[hid]; break; }
                }
                cout << (found == -1 ? -1 : rev[found]) << '\n';
            }
        } else if (t == 2) {
            int u; cin >> u;
            int len = n - sz[u];
            if (len <= 2*B) {
                outtre(u, tmp);
                int cc = procbig(tmp);
                cout << (cc == -1 ? -1 : rev[cc]) << '\n';
            } else {
                int found = -1;
                for (int hid = 0; hid < H; ++hid) {
                    int cntc = total_heavy[hid] - sub_heavy[hid][u];
                    if (cntc * 2 > len) { found = heavy_[hid]; break; }
                }
                cout << (found == -1 ? -1 : rev[found]) << '\n';
            }
        } else if (t == 3) {
            int u, v; cin >> u >> v;
            int L = lca(u, v);
            int len = depth[u] + depth[v] - 2*depth[L] + 1;
            if (len <= 2*B) {
                enum_path(u, v, tmp);
                int cc = procbig(tmp);
                cout << (cc == -1 ? -1 : rev[cc]) << '\n';
            } else {
                int found = -1;
                for (int hid = 0; hid < H; ++hid) {
                    int c = heavy_[hid];
                    int cntc = up_heavy[hid][u] + up_heavy[hid][v] - 2*up_heavy[hid][L] + (col[L] == c ? 1 : 0);
                    if (cntc * 2 > len) { found = c; break; }
                }
                cout << (found == -1 ? -1 : rev[found]) << '\n';
            }
        } else {

            if (t == 0) { cout << -1 << '\n'; }
            else {

                if (t == 4) { int x; cin >> x; cout << -1 << '\n'; }
                else cout << -1 << '\n';
            }
        }
    }
}