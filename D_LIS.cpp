const int logn = 20;

vector<int> calc_pre(int n, const vector<int>& p) {
    vector<int> bit(n + 1, 0);

    for (int i = 1; i <= n; i++) {
        int x = p[i] - 1;
        int res = 0;

        while (x > 0) {
            res = max(res, bit[x]);
            x -= x & -x;
        }

        int cur = res + 1;
        int y = p[i];

        while (y <= n) {
            bit[y] = max(bit[y], cur);
            y += y & -y;
        }
    }

    vector<int> pre(n + 1);

    for (int i = 1; i <= n; i++) {
        int x = p[i] - 1;
        int res = 0;

        while (x > 0) {
            res = max(res, bit[x]);
            x -= x & -x;
        }

        pre[i] = res + 1;
    }

    return pre;
}

int get_lca(int u, int v, const vector<int>& depth, const vector<vector<int>>& up) {
    if (u == v) {
        return u;
    }

    if (depth[u] < depth[v]) {
        swap(u, v);
    }

    int diff = depth[u] - depth[v];

    for (int k = 0; diff > 0; k++, diff >>= 1) {
        if (diff & 1) {
            u = up[u][k];
        }
    }

    if (u == v) {
        return u;
    }

    int top_k = 31 - __builtin_clz(depth[u]);

    for (int k = top_k; k >= 0; k--) {
        if (up[u][k] != up[v][k]) {
            u = up[u][k];
            v = up[v][k];
        }
    }

    return up[u][0];
}

vector<vector<int>> build_st(const vector<int>& layer, int m, const vector<int>& depth, const vector<vector<int>>& up) {
    int max_log = 31 - __builtin_clz(m);

    vector<vector<int>> st(max_log + 1, vector<int>(m + 1, 0));

    for (int i = 1; i <= m; i++) {
        st[0][i] = layer[i];
    }

    for (int j = 1; j <= max_log; j++) {
        int step = 1 << (j - 1);

        for (int i = 1; i + (1 << j) - 1 <= m; i++) {
            st[j][i] = get_lca(st[j - 1][i], st[j - 1][i + step], depth, up);
        }
    }

    return st;
}

int query_st(const vector<vector<int>>& st, int l, int r, const vector<int>& depth, const vector<vector<int>>& up) {
    int len = r - l + 1;
    int k_bit = 31 - __builtin_clz(len);

    return get_lca(st[k_bit][l], st[k_bit][r - (1 << k_bit) + 1], depth, up);
}

vector<int> solve_half(int n, const vector<int>& p) {
    vector<int> pre = calc_pre(n, p);

    int max_k = 0;

    for (int i = 1; i <= n; i++) {
        max_k = max(max_k, pre[i]);
    }

    vector<vector<int>> layers(max_k + 1);

    for (int i = 1; i <= n; i++) {
        layers[pre[i]].push_back(i);
    }

    vector<vector<int>> up(n + 1, vector<int>(logn, 0));
    vector<int> depth(n + 1, 0);

    debug(max_k);

    for (int i = 0; i < (int)layers[1].size(); i++) {
        int u = layers[1][i];

        depth[u] = 1;

        for (int j = 0; j < logn; j++) {
            up[u][j] = 0;
        }
    }

    vector<vector<int>> prev_st;

    if (max_k >= 1 && !layers[1].empty()) {
        vector<int> layer(1);

        for (int i = 1; i <= (int)layers[1].size(); i++) {
            layer.push_back(layers[1][i - 1]);
        }

        prev_st = build_st(layer, (int)layers[1].size(), depth, up);
    }

    for (int k = 2; k <= max_k; k++) {
        vector<int> prev_layer(1);

        for (int i = 1; i <= (int)layers[k - 1].size(); i++) {
            prev_layer.push_back(layers[k - 1][i - 1]);
        }

        int sz = (int)layers[k].size();

        debug(k, sz);

        for (int t = 1; t <= sz; t++) {
            int i = layers[k][t - 1];

            int lo = 1, hi = (int)layers[k - 1].size();
            int r = 0;

            while (lo <= hi) {
                int mid = (lo + hi) / 2;

                if (prev_layer[mid] < i) {
                    r = mid;
                    lo = mid + 1;
                } else {
                    hi = mid - 1;
                }
            }

            int l = r;

            lo = 1;
            hi = r;

            while (lo <= hi) {
                int mid = (lo + hi) / 2;

                if (p[prev_layer[mid]] < p[i]) {
                    l = mid;
                    hi = mid - 1;
                } else {
                    lo = mid + 1;
                }
            }

            int cur_idom = query_st(prev_st, l, r, depth, up);

            depth[i] = depth[cur_idom] + 1;
            up[i][0] = cur_idom;

            for (int j = 1; j < logn; j++) {
                up[i][j] = up[up[i][j - 1]][j - 1];
            }

            if (k <= 3) {
                debug(i, l, r, cur_idom, depth[i]);
            }
        }

        if (k < max_k) {
            vector<int> layer(1);

            for (int i = 1; i <= (int)layers[k].size(); i++) {
                layer.push_back(layers[k][i - 1]);
            }

            prev_st = build_st(layer, (int)layers[k].size(), depth, up);
        }
    }

    vector<int> res(n + 1);

    for (int i = 1; i <= n; i++) {
        res[i] = depth[i] - 1;
    }

    return res;
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(0);

    int n;
    cin >> n;

    vector<int> p(n + 1);

    for (int i = 1; i <= n; i++) {
        cin >> p[i];
    }

    debug(n);

    vector<int> ans_left = solve_half(n, p);

    vector<int> q(n + 1);

    for (int i = 1; i <= n; i++) {
        q[i] = n + 1 - p[n - i + 1];
    }

    vector<int> ans_rev = solve_half(n, q);

    for (int i = 1; i <= n; i++) {
        int ans_right = ans_rev[n - i + 1];

        cout << ans_left[i] + ans_right;

        if (i < n) {
            cout << ' ';
        }
    }

    cout << '\n';

    debug(ans_left, ans_rev);
}