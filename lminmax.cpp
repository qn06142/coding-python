int main() {
    int n;
    long long d;
    cin >> n >> d;

    vector<int> a(n + 1);
    for (int i = 1; i <= n; i++) {
        cin >> a[i];
    }

    deque<int> dq1, dq2;
    int l = 1, ans = 0;

    for (int i = 1; i <= n; i++) {
        while (!dq1.empty() && a[dq1.back()] <= a[i]) {
            dq1.pop_back();
        }
        dq1.push_back(i);
        while (!dq2.empty() && a[dq2.back()] >= a[i]) {
            dq2.pop_back();
        }
        dq2.push_back(i);

        while (a[dq1.front()] - a[dq2.front()] > d) {
            if (dq1.front() == l) {
                dq1.pop_front();
            }
            if (dq2.front() == l) {
                dq2.pop_front();
            }
            ++l;
        }

        ans = max(ans, i - l + 1);
    }

    cout << ans << "\n";
}