const long long MOD = 1000000007;

int main(){
    ifstream fin("BUILDTREE.INP");
    ofstream fout("BUILDTREE.OUT");
    int n, m;
    fin >> n >> m;
    vector<long long> w(m);
    for (int i = 0; i < m; ++i) fin >> w[i];

    int edge = n - m - 1; 
    vector<vector<pair<int,long long>>> adj(n);
    for (int i = 0; i < edge; ++i){
        int u,v; long long c;
        fin >> u >> v >> c;
        --u; --v;
        adj[u].push_back({v,c});
        adj[v].push_back({u,c});
    }

    vector<char> vis(n, 0);
    vector<int> comp_id(n, -1);
    vector<long long> compsz; compsz.reserve(m+1);
    vector<long long> compsum; compsum.reserve(m+1);
    vector<long long> compmind; compmind.reserve(m+1);

    for (int root = 0; root < n; ++root){
        if (vis[root]) continue;

        vector<int> stack{root};
        vis[root] = 1;
        vector<int> nodes;
        while(!stack.empty()){
            int u = stack.back(); stack.pop_back();
            nodes.push_back(u);
            for (auto &pr: adj[u]){
                int v = pr.first;
                if (!vis[v]){
                    vis[v] = 1;
                    stack.push_back(v);
                }
            }
        }
        int s = (int)nodes.size();

        unordered_map<int,int> idx; idx.reserve(s*2);
        for (int i=0;i<s;++i){ idx[nodes[i]] = i; comp_id[nodes[i]] = (int)compsz.size(); }

        vector<vector<pair<int,long long>>> ladj(s);
        for (int i=0;i<s;++i){
            int u = nodes[i];
            for (auto &pr: adj[u]){
                int v = pr.first; long long c = pr.second;
                if (comp_id[v] == comp_id[u]){ 

                    int lu = i, lv = idx[v];
                    ladj[lu].push_back({lv,c});
                }
            }
        }

        if (s == 1){
            compsz.push_back(1);
            compsum.push_back(0);
            compmind.push_back(0);
            continue;
        }

        vector<int> parent(s, -1), order; order.reserve(s);
        vector<int> st2; st2.reserve(s);
        parent[0] = -2;
        st2.push_back(0);
        while(!st2.empty()){
            int u = st2.back(); st2.pop_back();
            order.push_back(u);
            for (auto &pr: ladj[u]){
                int v = pr.first;
                if (parent[v] == -1){
                    parent[v] = u;
                    st2.push_back(v);
                }
            }
        }

        vector<long long> subtree(s,1);
        vector<long long> sum_down(s,0); 
        for (int i = (int)order.size()-1; i>=0; --i){
            int u = order[i];
            for (auto &pr: ladj[u]){
                int v = pr.first; long long c = pr.second;
                if (parent[v] == u){
                    subtree[u] += subtree[v];
                    sum_down[u] += sum_down[v] + subtree[v]*c;
                }
            }
        }

        vector<long long> sumdist(s,0);
        sumdist[0] = sum_down[0];
        for (int u : order){
            for (auto &pr: ladj[u]){
                int v = pr.first; long long c = pr.second;
                if (parent[v] == u){

                    sumdist[v] = sumdist[u] + c * ( (long long)s - 2*subtree[v] );
                }
            }
        }

        __int128 compinternal = 0;
        for (int u = 0; u < s; ++u){
            for (auto &pr: ladj[u]){
                int v = pr.first; long long c = pr.second;
                if (parent[v] == u){
                    compinternal += (__int128)c * (__int128)subtree[v] * (__int128)(s - subtree[v]);
                }
            }
        }

        long long minsd = sumdist[0];
        for (int i = 1; i < s; ++i) if (sumdist[i] < minsd) minsd = sumdist[i];

        compsz.push_back(s);
        compsum.push_back((long long)compinternal);
        compmind.push_back(minsd);
    } 

    int k = (int)compsz.size(); 

    __int128 toti = 0;
    for (auto x: compsum) toti += (__int128)x;

    __int128 tota = 0;
    for (int i = 0; i < k; ++i){
        tota += (__int128)compmind[i] * (__int128)(n - compsz[i]);
    }

    int center = 0;
    for (int i = 1; i < k; ++i) if (compsz[i] > compsz[center]) center = i;
    vector<__int128> P; P.reserve(k-1);
    for (int i = 0; i < k; ++i){
        if (i == center) continue;
        __int128 s = compsz[i];
        __int128 val = s * (__int128)(n - (long long)s);
        P.push_back(val);
    }
    sort(P.begin(), P.end()); 

    sort(w.begin(), w.end(), greater<long long>()); 

    __int128 cc = 0;
    for (int i = 0; i < (int)P.size(); ++i){
        __int128 prod = P[i] * (__int128)w[i];
        cc += prod;
    }

    __int128 total = toti + tota + cc;

    long long ans = (long long)(total % (__int128)MOD);
    if (ans < 0) ans += MOD;
    fout << ans << "\n";
    return 0;
}