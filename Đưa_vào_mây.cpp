const int maxn = 100005;
const int lg = 17;

struct stor {
    int v;
    long long w;
};

struct stor1 {
    int u, v;
    long long w;
};

vector<stor> g[maxn], tr[maxn];

int par[maxn];

int find(int x) {
    return par[x] == x ? x : par[x] = find(par[x]);
}

int up[maxn][lg + 1];
int dep[maxn];
long long dis[maxn];

void dfs(int u, int p) {
    up[u][0] = p;
    for (int i = 1; i <= lg; i++)
        up[u][i] = up[up[u][i - 1]][i - 1];

    for (auto e : tr[u]) {
        if (e.v == p) continue;
        dep[e.v] = dep[u] + 1;
        dis[e.v] = dis[u] + e.w;
        dfs(e.v, u);
    }
}

int lca(int u, int v) {
    if (dep[u] < dep[v]) swap(u, v);

    int d = dep[u] - dep[v];
    for (int i = lg; i >= 0; i--)
        if (d >> i & 1)
            u = up[u][i];

    if (u == v) return u;

    for (int i = lg; i >= 0; i--) {
        if (up[u][i] != up[v][i]) {
            u = up[u][i];
            v = up[v][i];
        }
    }

    return up[u][0];
}

long long dist(int u, int v) {
    int w = lca(u, v);
    return dis[u] + dis[v] - 2 * dis[w];
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n, m;
    cin >> n >> m;

    for (int i = 1; i <= n; i++)
        par[i] = i;

    vector<stor1> ext;
    vector<int> sp;

    for (int i = 1; i <= m; i++) {
        int u, v;
        long long w;
        cin >> u >> v >> w;

        g[u].push_back({v, w});
        g[v].push_back({u, w});

        int fu = find(u);
        int fv = find(v);

        if (fu != fv) {
            par[fu] = fv;
            tr[u].push_back({v, w});
            tr[v].push_back({u, w});
        } else {
            ext.push_back({u, v, w});
            sp.push_back(u);
            sp.push_back(v);
        }
    }

    sort(sp.begin(), sp.end());
    sp.erase(unique(sp.begin(), sp.end()), sp.end());

    dfs(1, 0);

    int k = sp.size();

    vector<vector<long long>> d(k, vector<long long>(n + 1, LLONG_MAX));

    for (int i = 0; i < k; i++) {
        int s = sp[i];

        priority_queue<
            pair<long long,int>,
            vector<pair<long long,int>>,
            greater<pair<long long,int>>
        > pq;

        d[i][s] = 0;
        pq.push({0, s});

        while (!pq.empty()) {
            auto [cd, u] = pq.top();
            pq.pop();

            if (cd != d[i][u]) continue;

            for (auto e : g[u]) {
                if (d[i][e.v] > cd + e.w) {
                    d[i][e.v] = cd + e.w;
                    pq.push({d[i][e.v], e.v});
                }
            }
        }
    }

    int q;
    cin >> q;

    while (q--) {
        int u, v;
        cin >> u >> v;

        long long ans = dist(u, v);

        for (int i = 0; i < k; i++)
            ans = min(ans, d[i][u] + d[i][v]);

        cout << ans << '\n';
    }
}