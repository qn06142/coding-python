const int maxn = 100000 + 5;
const int maxm = 200000 + 5; 

int n;

int head[maxn], to[maxm], nxt[maxm], edge_idx;

int colorv[maxn]; 
int sz_arr[maxn];
int heavy[maxn];
int tin[maxn], tout[maxn], tour[maxn];
int timer = 0;

int cnt[maxn];             
long long sumcnt[maxn];    
int max_ = 0;

long long answer[maxn];

void add_edge(int u, int v){
    to[edge_idx] = v;
    nxt[edge_idx] = head[u];
    head[u] = edge_idx++;
}

void dfs_sz(int u, int p){
    tin[u] = timer;
    tour[timer++] = u;
    sz_arr[u] = 1;
    heavy[u] = -1;
    int best = 0;
    for(int e = head[u]; e != -1; e = nxt[e]){
        int v = to[e];
        if(v == p) continue;
        dfs_sz(v, u);
        sz_arr[u] += sz_arr[v];
        if(sz_arr[v] > best){
            best = sz_arr[v];
            heavy[u] = v;
        }
    }
    tout[u] = timer - 1;
}

inline void add_node(int node){
    int c = colorv[node];
    int old = cnt[c];
    if(old > 0) sumcnt[old] -= c;
    int nw = old + 1;
    cnt[c] = nw;
    sumcnt[nw] += c;
    if(nw > max_) max_ = nw;
}

void add_subtree(int u){
    for(int i = tin[u]; i <= tout[u]; ++i){
        add_node(tour[i]);
    }
}

void clear_subtree(int u){
    for(int i = tin[u]; i <= tout[u]; ++i){
        int node = tour[i];
        int c = colorv[node];
        int f = cnt[c];
        if(f > 0){
            sumcnt[f] -= c;
            cnt[c] = 0;
        }
    }
    max_ = 0;
}

void dfs(int u, int p, bool keep){

    for(int e = head[u]; e != -1; e = nxt[e]){
        int v = to[e];
        if(v == p || v == heavy[u]) continue;
        dfs(v, u, false);
    }

    if(heavy[u] != -1){
        dfs(heavy[u], u, true);
    }

    for(int e = head[u]; e != -1; e = nxt[e]){
        int v = to[e];
        if(v == p || v == heavy[u]) continue;
        add_subtree(v);
    }

    add_node(u);

    answer[u] = sumcnt[max_];

    if(!keep){
        clear_subtree(u);
    }
}

int main(){
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    if(!(cin >> n)) return 0;

    for(int i = 1; i <= n; ++i) cin >> colorv[i];

    for(int i = 1; i <= n; ++i) head[i] = -1;
    edge_idx = 0;

    for(int i = 0; i < n-1; ++i){
        int u, v;
        cin >> u >> v;
        add_edge(u, v);
        add_edge(v, u);
    }

    for(int i = 1; i <= n; ++i){
        sz_arr[i] = 0;
        heavy[i] = -1;
        tin[i] = tout[i] = 0;
    }
    timer = 0;

    dfs_sz(1, 0);

    for(int i = 0; i <= n; ++i){
        cnt[i] = 0;
        sumcnt[i] = 0;
    }
    max_ = 0;

    dfs(1, 0, true);

    for(int i = 1; i <= n; ++i){
        cout << answer[i] << ' ';
    }
}