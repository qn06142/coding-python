const int maxn = 200005;

struct edge {
    int to;
    long long w, c;
};

struct point {
    long long l, t;

    bool operator<(const point& other) const {
        return l < other.l;
    }
};

int n, sz[maxn], bit[maxn], n_;
long long a, b, ans = 0, vals[maxn];
bool removed[maxn];
vector<edge> adj[maxn];
point allpts[maxn], subpts[maxn];
int dbgcnt = 0;

inline void update(int i, int v) {
    for (; i <= n_; i += i & -i) {
        bit[i] += v;
    }
}

inline int query(int i) {
    int res = 0;

    for (; i > 0; i -= i & -i) {
        res += bit[i];
    }

    return res;
}

void getsize(int u, int p) {
    sz[u] = 1;

    for (int i = 0; i < (int)adj[u].size(); i++) {
        edge e = adj[u][i];

        if (e.to != p && !removed[e.to]) {
            getsize(e.to, u);
            sz[u] += sz[e.to];
        }
    }
}

int centroids(int u, int p, int total) {
    for (int i = 0; i < (int)adj[u].size(); i++) {
        edge e = adj[u][i];

        if (e.to != p && !removed[e.to]) {
            if (sz[e.to] > total / 2) {
                return centroids(e.to, u, total);
            }
        }
    }

    return u;
}

void getpoints(int u, int p, long long l, long long t, point pts[], int& cnt) {
    pts[++cnt] = {l, t};

    for (int i = 0; i < (int)adj[u].size(); i++) {
        edge e = adj[u][i];

        if (e.to != p && !removed[e.to]) {
            getpoints(e.to, u, l + e.w, t + e.c, pts, cnt);
        }
    }
}

int rank_(long long x, int m) {
    return upper_bound(vals + 1, vals + m + 1, x) - vals - 1;
}

long long count(point pts[], int cnt) {
    if (cnt <= 0) {
        return 0;
    }

    sort(pts + 1, pts + cnt + 1);

    for (int i = 1; i <= cnt; i++) {
        vals[i] = pts[i].t;
    }

    sort(vals + 1, vals + cnt + 1);

    int m = unique(vals + 1, vals + cnt + 1) - vals - 1;
    n_ = m;

    for (int i = 1; i <= cnt; i++) {
        update(rank_(pts[i].t, m), 1);
    }

    int r = cnt;
    long long ordered = 0;

    for (int i = 1; i <= cnt; i++) {
        while (r >= 1 && pts[i].l + pts[r].l > a) {
            update(rank_(pts[r].t, m), -1);
            r--;
        }

        if (r < 1) {
            break;
        }

        int ranklim = rank_(b - pts[i].t, m);

        if (ranklim > 0) {
            ordered += query(ranklim);
        }

        if (2 * pts[i].l <= a && 2 * pts[i].t <= b) {
            ordered--;
        }
    }

    for (int i = 1; i <= r; i++) {
        update(rank_(pts[i].t, m), -1);
    }

    return ordered / 2;
}

void decompose(int u) {
    getsize(u, 0);

    int c = centroids(u, 0, sz[u]);
    removed[c] = true;

    int allcnt = 1;
    allpts[1] = {0, 0};

    for (int i = 0; i < (int)adj[c].size(); i++) {
        edge e = adj[c][i];

        if (!removed[e.to]) {
            int subcnt = 0;

            getpoints(e.to, c, e.w, e.c, subpts, subcnt);

            ans -= count(subpts, subcnt);

            for (int j = 1; j <= subcnt; j++) {
                allpts[++allcnt] = subpts[j];
            }
        }
    }

    ans += count(allpts, allcnt);

    if (dbgcnt < 5) {
        debug(c, allcnt, ans);
        dbgcnt++;
    }

    for (int i = 0; i < (int)adj[c].size(); i++) {
        edge e = adj[c][i];

        if (!removed[e.to]) {
            decompose(e.to);
        }
    }
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(0);
    cin >> n >> a >> b;

    for (int i = 1; i < n; i++) {
        int u, v;
        long long w, c;
        cin >> u >> v >> w >> c;

        adj[u].push_back({v, w, c});
        adj[v].push_back({u, w, c});
    }

    debug(n, a, b);

    decompose(1);

    debug(ans);

    cout << ans;
}