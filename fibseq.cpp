const long long MOD = 1000000007LL;

struct Matrix {
    long long a[2][2];

    Matrix() {
        memset(a, 0, sizeof(a));
    }

    static Matrix identity() {
        Matrix I;
        I.a[0][0] = 1;
        I.a[1][1] = 1;
        return I;
    }

    Matrix operator*(const Matrix &b) const {
        Matrix res;
        res.a[0][0] = (a[0][0] * b.a[0][0] + a[0][1] * b.a[1][0]) % MOD;
        res.a[0][1] = (a[0][0] * b.a[0][1] + a[0][1] * b.a[1][1]) % MOD;
        res.a[1][0] = (a[1][0] * b.a[0][0] + a[1][1] * b.a[1][0]) % MOD;
        res.a[1][1] = (a[1][0] * b.a[0][1] + a[1][1] * b.a[1][1]) % MOD;
        return res;
    }

    Matrix operator+(const Matrix &b) const {
        Matrix res;
        res.a[0][0] = (a[0][0] + b.a[0][0]) % MOD;
        res.a[0][1] = (a[0][1] + b.a[0][1]) % MOD;
        res.a[1][0] = (a[1][0] + b.a[1][0]) % MOD;
        res.a[1][1] = (a[1][1] + b.a[1][1]) % MOD;
        return res;
    }
};
pair<long long, long long> fib(long long n) {
    if (n == 0) return {0, 1};
    auto p = fib(n >> 1);
    long long c = (p.first * (2 * p.second - p.first + MOD)) % MOD;
    long long d = (p.first * p.first + p.second * p.second) % MOD;
    if (n & 1) {
        return {d, (c + d) % MOD};
    } else {
        return {c, d};
    }
}

Matrix power_fib(long long v) {
    if (v == 0) return Matrix::identity();
    auto [fv, fv1] = fib(v);
    Matrix res;
    res.a[0][0] = fv1;
    res.a[0][1] = fv;
    res.a[1][0] = fv;
    res.a[1][1] = (fv1 - fv + MOD) % MOD;
    return res;
}

Matrix fib_init(long long k) {
    return power_fib(k);
}

const int maxn = 200005;

struct Node {
    Matrix val;
    long long lazy;
    void apply(long long v) {
        val = val * power_fib(v);
        lazy += v;
    }
};

Node tree[4 * maxn];
int a[maxn];

void push(int node) {
    if (tree[node].lazy != 0) {
        tree[2 * node].apply(tree[node].lazy);
        tree[2 * node + 1].apply(tree[node].lazy);
        tree[node].lazy = 0;
    }
}

void build(int node, int l, int r) {
    tree[node].lazy = 0;
    if (l == r) {
        tree[node] = {fib_init(a[l]), 0};
        return;
    }
    int mid = (l + r) / 2;
    build(2 * node, l, mid);
    build(2 * node + 1, mid + 1, r);
    tree[node].val = tree[2 * node].val + tree[2 * node + 1].val;
}

void update(int node, int l, int r, int ql, int qr, long long val) {
    if (ql > r || qr < l) return;
    if (ql <= l && r <= qr) {
        tree[node].apply(val);
        return;
    }
    push(node);
    int mid = (l + r) / 2;
    update(2 * node, l, mid, ql, qr, val);
    update(2 * node + 1, mid + 1, r, ql, qr, val);
    tree[node].val = tree[2 * node].val + tree[2 * node + 1].val;
}

Node query(int node, int l, int r, int ql, int qr) {
    if (ql > r || qr < l) return {Matrix::identity(), 0};
    if (ql <= l && r <= qr) return tree[node];
    push(node);
    int mid = (l + r) / 2;
    Node left_res = query(2 * node, l, mid, ql, qr);
    Node right_res = query(2 * node + 1, mid + 1, r, ql, qr);
    return {left_res.val + right_res.val, 0};
}

