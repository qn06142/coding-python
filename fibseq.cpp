    cin >> n >> q;
    build(1, 1, n);
    while (q--) {
        char t;
        cin >> t;
        if (t == 'D') {
            int l, r;
            cin >> l >> r;
            update(1, 1, n, l, r, 1);
        } else {
            int l, r;
            cin >> l >> r;
            cout << query(1, 1, n, l, r).val.a[0][1] << '\n';
        }
    }
