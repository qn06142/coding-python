int n = 0, m = 0;
vector<int> headf, tof, nxtf;   
vector<int> headr, tor, nxtr;   

vector<char> vis;
vector<int> order;        
vector<int> comp;         

void build(const vector<int> &u, const vector<int> &v) {
    headf.assign(n + 1, -1);
    tof.assign(m + 1, -1);
    nxtf.assign(m + 1, -1);
    headr.assign(n + 1, -1);
    tor.assign(m + 1, -1);
    nxtr.assign(m + 1, -1);

    for (int i = 1; i <= m; ++i) {
        int uu = u[i], vv = v[i];
        tof[i] = vv;
        nxtf[i] = headf[uu];
        headf[uu] = i;

        tor[i] = uu;
        nxtr[i] = headr[vv];
        headr[vv] = i;
    }
}

void dfs1(int v) {
    vis[v] = 1;
    for (int e = headf[v]; e != -1; e = nxtf[e]) {
        int u = tof[e];
        if (!vis[u]) dfs1(u);
    }
    order.push_back(v);
}

void dfs2(int v, int cid) {
    comp[v] = cid;
    for (int e = headr[v]; e != -1; e = nxtr[e]) {
        int u = tor[e];
        if (comp[u] == -1) dfs2(u, cid);
    }
}

long long full_yield(long long x) {
    if (x <= 0) return 0LL;

    long double D = sqrtl(1.0L + 8.0L * (long double)x);
    long long r = (long long) floor((D - 1.0L) / 2.0L);

    while (r >= 0 && (__int128)r * (r + 1) / 2 >= (__int128)x) --r;
    while ((__int128)(r + 1) * (r + 2) / 2 < (__int128)x) ++r;

    long long t = r + 1;
    if (t <= 0) return 0LL;

    __int128 term1 = (__int128)t * (__int128)x;
    __int128 tt = (__int128)t;
    __int128 sub = (tt - 1) * tt * (tt + 1) / 6;
    __int128 res = term1 - sub;
    if (res < 0) res = 0;
    return (long long)res;
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);
    cin >> n >> m;

    vector<int> u(m + 1), v(m + 1);
    vector<long long> w_(m + 1);
    for (int i = 1; i <= m; ++i) {
        int x, y; long long w;
        cin >> x >> y >> w;
        u[i] = x;     
        v[i] = y;     
        w_[i] = w;
    }
    int s; cin >> s; 

    build(u, v);

    vis.assign(n + 1, 0);
    order.clear();
    order.reserve(n);
    for (int i = 1; i <= n; ++i) if (!vis[i]) dfs1(i);

    comp.assign(n + 1, -1);
    int comp_cnt = 0;
    for (int i = (int)order.size() - 1; i >= 0; --i) {
        int vv = order[i];
        if (comp[vv] == -1) {
            dfs2(vv, comp_cnt++);
        }
    }

    vector<long long> internal_sum(comp_cnt, 0LL);
    vector<int> head_c(comp_cnt, -1);
    vector<int> to_c(m + 1, -1), nxt_c(m + 1, -1);
    vector<long long> w_c(m + 1, 0LL);
    vector<int> indeg(comp_cnt, 0);
    int e2cnt = 0;

    for (int i = 1; i <= m; ++i) {
        int a = u[i], b = v[i];
        int ca = comp[a], cb = comp[b];
        if (ca == cb) {
            internal_sum[ca] += full_yield(w_[i]);
        } else {
            ++e2cnt;
            to_c[e2cnt] = cb;
            nxt_c[e2cnt] = head_c[ca];
            head_c[ca] = e2cnt;
            w_c[e2cnt] = w_[i];
            ++indeg[cb];
        }
    }

    deque<int> dq;
    for (int i = 0; i < comp_cnt; ++i) if (indeg[i] == 0) dq.push_back(i);
    vector<int> topo; topo.reserve(comp_cnt);
    while (!dq.empty()) {
        int vtx = dq.front(); dq.pop_front();
        topo.push_back(vtx);
        for (int e = head_c[vtx]; e != -1; e = nxt_c[e]) {
            int to = to_c[e];
            --indeg[to];
            if (indeg[to] == 0) dq.push_back(to);
        }
    }

    vector<long long> dp(comp_cnt, 0LL);
    for (int idx = (int)topo.size() - 1; idx >= 0; --idx) {
        int vtx = topo[idx];
        long long best_ext = 0;
        for (int e = head_c[vtx]; e != -1; e = nxt_c[e]) {
            int to = to_c[e];
            long long cand = w_c[e] + dp[to];
            if (cand > best_ext) best_ext = cand;
        }
        dp[vtx] = internal_sum[vtx] + best_ext;
    }

    cout << dp[ comp[s] ] << '\n';
}