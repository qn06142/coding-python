const int maxn = 65;
const int maxelite = 8;

struct point {
    double x, y;
};

struct candidate {
    double score;
    point pts[maxn];

    bool operator<(const candidate& other) const {
        return score > other.score;
    }
};

point bestpts[maxn], pts[maxn];
point elitepts[maxelite + 2][maxn];
candidate elite[maxelite + 2];

double fx[maxn], fy[maxn], dmin[maxn];
double dmat[maxn][maxn], dxmat[maxn][maxn], dymat[maxn][maxn];
double bestb = -1.0;
int ecnt = 0;

inline double distsq(const point& a, const point& b) {
    double dx = a.x - b.x, dy = a.y - b.y;
    return dx * dx + dy * dy;
}

inline double dist(const point& a, const point& b) {
    return sqrt(distsq(a, b));
}

inline double fastpow(double base, int exp) {
    double res = 1.0;

    while (exp > 0) {
        if (exp & 1) {
            res *= base;
        }

        base *= base;
        exp >>= 1;
    }

    return res;
}

void project(point& p, double r, mt19937& rng) {
    p.x = clamp(p.x, 0.0, 1000.0);
    p.y = clamp(p.y, 0.0, 1000.0);

    if (r > 0.0) {
        double dx = p.x - 500.0;
        double dy = p.y - 500.0;
        double d2 = dx * dx + dy * dy;
        double r2 = r * r;

        if (d2 < r2) {
            double d = sqrt(d2);

            if (d < 1e-7) {
                uniform_real_distribution<double> ang(0.0, 2.0 * acos(-1.0));
                double theta = ang(rng);
                dx = cos(theta);
                dy = sin(theta);
                d = 1.0;
            }

            p.x = 500.0 + dx / d * r;
            p.y = 500.0 + dy / d * r;

            p.x = clamp(p.x, 0.0, 1000.0);
            p.y = clamp(p.y, 0.0, 1000.0);
        }
    }
}

double mindist(point p[], int n) {
    double res = 1e18;

    for (int i = 1; i <= n; i++) {
        for (int j = i + 1; j <= n; j++) {
            res = min(res, distsq(p[i], p[j]));
        }
    }

    return sqrt(res);
}

void initpoints(int n, double r, mt19937& rng, point p[]) {
    uniform_real_distribution<double> coord(0.0, 1000.0);

    p[1] = {0.0, 0.0};

    int candidates = max(60, min(150, n * 3));

    for (int i = 2; i <= n; i++) {
        point bestcand = {0, 0};
        double bestdist = -1.0;

        for (int k = 1; k <= candidates; k++) {
            point cand = {coord(rng), coord(rng)};
            project(cand, r, rng);

            double curdist = 1e18;

            for (int j = 1; j < i; j++) {
                curdist = min(curdist, distsq(cand, p[j]));

                if (curdist <= bestdist) {
                    break;
                }
            }

            if (curdist > bestdist) {
                bestdist = curdist;
                bestcand = cand;
            }
        }

        p[i] = bestcand;
    }
}

void optimize(point p[], int n, double r, int steps, double startstep, double endstep, int minexp, int maxexp, mt19937& rng) {
    for (int it = 0; it < steps; it++) {
        double progress = (double)it / steps;
        double stepsize = startstep * pow(endstep / startstep, progress);
        int exp = minexp + (int)((maxexp - minexp) * progress * progress);

        for (int i = 1; i <= n; i++) {
            dmin[i] = 1e18;
            fx[i] = 0.0;
            fy[i] = 0.0;
        }

        for (int i = 1; i <= n; i++) {
            for (int j = i + 1; j <= n; j++) {
                double dx = p[i].x - p[j].x;
                double dy = p[i].y - p[j].y;
                double d = sqrt(dx * dx + dy * dy);

                if (d < 1e-4) {
                    d = 1e-4;
                }

                dmat[i][j] = d;
                dmat[j][i] = d;
                dxmat[i][j] = dx / d;
                dymat[i][j] = dy / d;
                dxmat[j][i] = -dxmat[i][j];
                dymat[j][i] = -dymat[i][j];

                dmin[i] = min(dmin[i], d);
                dmin[j] = min(dmin[j], d);
            }
        }

        for (int i = 1; i <= n; i++) {
            double dm = dmin[i];

            for (int j = 1; j <= n; j++) {
                if (i == j) {
                    continue;
                }

                double ratio = dm / dmat[i][j];

                if (ratio < 0.25) {
                    continue;
                }

                double weight = fastpow(ratio, exp);

                fx[i] += dxmat[i][j] * weight;
                fy[i] += dymat[i][j] * weight;
            }
        }

        for (int i = 1; i <= n; i++) {
            double flen = sqrt(fx[i] * fx[i] + fy[i] * fy[i]);

            if (flen > 1e-9) {
                double scale = stepsize / max(1.0, flen);
                p[i].x += fx[i] * scale;
                p[i].y += fy[i] * scale;
            }

            project(p[i], r, rng);
        }
    }
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(0);

    int n, r;
    double a;

    if (!(cin >> n >> r >> a)) {
        return 0;
    }

    mt19937 rng(1337);
    chrono::steady_clock::time_point starttime = chrono::steady_clock::now();

    const double explorebudget = 1.45;
    const double totalbudget = 1.82;

    double expecteddist = 1050.0 / sqrt(n);
    double initstep = clamp(expecteddist * 0.18, 12.0, 45.0);
    int exploresteps = n <= 25 ? 450 : 650;
    int iters = 0;

    debug(n, r, a, expecteddist, initstep, exploresteps);

    while (true) {
        chrono::steady_clock::time_point curtime = chrono::steady_clock::now();
        double elapsed = chrono::duration<double>(curtime - starttime).count();

        if (elapsed > explorebudget) {
            break;
        }

        initpoints(n, r, rng, pts);
        optimize(pts, n, r, exploresteps, initstep, 0.15, 3, 22, rng);

        double curb = mindist(pts, n);

        if (curb > bestb) {
            bestb = curb;

            for (int i = 1; i <= n; i++) {
                bestpts[i] = pts[i];
            }

            debug(iters, bestb);
        }

        int pos;

        if (ecnt < maxelite) {
            pos = ++ecnt;
        } else {
            pos = maxelite + 1;
        }

        elite[pos].score = curb;

        for (int i = 1; i <= n; i++) {
            elite[pos].pts[i] = pts[i];
        }

        if (ecnt == maxelite) {
            sort(elite + 1, elite + maxelite + 2);
        }

        if (pos > maxelite) {
            ecnt = maxelite;
        }

        iters++;
    }

    for (int i = 1; i <= ecnt; i++) {
        chrono::steady_clock::time_point curtime = chrono::steady_clock::now();
        double elapsed = chrono::duration<double>(curtime - starttime).count();

        if (elapsed > totalbudget) {
            break;
        }

        for (int j = 1; j <= n; j++) {
            pts[j] = elite[i].pts[j];
        }

        optimize(pts, n, r, 1800, 1.5, 0.002, 18, 45, rng);

        double curb = mindist(pts, n);

        if (curb > bestb) {
            bestb = curb;

            for (int j = 1; j <= n; j++) {
                bestpts[j] = pts[j];
            }

            debug(i, bestb);
        }
    }

    debug(iters, ecnt, bestb);

    cout << fixed << setprecision(4);

#ifdef ONLINE_JUDGE
    for (int i = 1; i <= n; i++) {
        cout << bestpts[i].x << ' ' << bestpts[i].y << '\n';
    }
#else
    cout << "Best B: " << bestb << " (Target A: " << a
         << ", Ratio B/A: " << bestb / a << ")\n";
#endif

    return 0;
}