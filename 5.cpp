const int maxn = 200005;
const long long mod = 1000000007LL;

struct Node {
    long long cnt, prod;
};

struct Fenwick {
    int n, tim;
    int tag[maxn];
    Node bit[maxn];

    void init(int _n) {
        n = _n;
        tim = 1;
        for (int i = 1; i <= n; i++) {
            tag[i] = 0;
            bit[i] = {0, 1};
        }
    }

    void clear() {
        ++tim;
    }

    void add(int idx, long long val) {
        for (; idx <= n; idx += idx & -idx) {
            if (tag[idx] != tim) {
                tag[idx] = tim;
                bit[idx] = {0, 1};
            }
            bit[idx].cnt++;
            bit[idx].prod = bit[idx].prod * val % mod;
        }
    }

    pair<long long, long long> qry(int idx) {
        long long cnt = 0, prod = 1;
        for (; idx > 0; idx -= idx & -idx) {
            if (tag[idx] == tim) {
                cnt += bit[idx].cnt;
                prod = prod * bit[idx].prod % mod;
            }
        }
        return {cnt, prod};
    }
};

struct edge {
    int to, w, t;
};

int n;
vector<edge> adj[maxn];

int tin[maxn], tout[maxn], ord[maxn], tim;
int dep[maxn];

int rc[maxn], bc[maxn];
int av[maxn], bv[maxn];
long long P[maxn], invP[maxn];

vector<int> comp1, comp2;

Fenwick bit1, bit2;

long long ac = 0, ap = 1;
long long ans = 1, lhs = 1, rhs = 1;

long long power(long long base, long long exp) {
    long long res = 1;
    base %= mod;
    while (exp > 0) {
        if (exp & 1) res = res * base % mod;
        base = base * base % mod;
        exp >>= 1;
    }
    return res;
}

long long inv(long long x) {
    return power(x, mod - 2);
}

void dfs(int u, int p) {
    tin[u] = ++tim;
    ord[tim] = u;

    av[u] = 2 * bc[u] - rc[u];
    bv[u] = 2 * rc[u] - bc[u];
    invP[u] = inv(P[u]);

    comp1.push_back(av[u]);
    comp2.push_back(bv[u]);

    for (auto &e : adj[u]) {
        int v = e.to;
        if (v == p) continue;

        dep[v] = dep[u] + 1;
        rc[v] = rc[u] + (e.t == 0);
        bc[v] = bc[u] + (e.t == 1);
        P[v] = P[u] * e.w % mod;
        dfs(v, u);
    }

    tout[u] = tim;
}

inline int subsz(int u) {
    return tout[u] - tin[u] + 1;
}

inline int idx1(const vector<int> &v, int x) {
    return lower_bound(v.begin(), v.end(), x) - v.begin() + 1;
}

inline int idx0(const vector<int> &v, int x) {
    return upper_bound(v.begin(), v.end(), x) - v.begin();
}

void query(int x, int u) {
    if (!ac) return;

    long long tot = power(P[x], ac) * ap % mod;
    tot = tot * power(invP[u], 2 * ac) % mod;
    ans = ans * tot % mod;
    int idA = idx0(comp1, 2 * av[u] - av[x] - 1);
    if (idA > 0) {
        auto [tmp, tmp1] = bit1.qry(idA);
        if (tmp) {
            long long cur = power(P[x], tmp) * tmp1 % mod;
            cur = cur * power(invP[u], 2 * tmp) % mod;
            lhs = lhs * cur % mod;
        }
    }
    int idB = idx0(comp2, 2 * bv[u] - bv[x] - 1);
    if (idB > 0) {
        auto [cntB, prodB] = bit2.qry(idB);
        if (cntB) {
            long long cur = power(P[x], cntB) * prodB % mod;
            cur = cur * power(invP[u], 2 * cntB) % mod;
            rhs = rhs * cur % mod;
        }
    }
}

void update(int x) {
    ++ac;
    ap = ap * P[x] % mod;

    bit1.add(idx1(comp1, av[x]), P[x]);
    bit2.add(idx1(comp2, bv[x]), P[x]);
}

void clear() {
    ac = 0;
    ap = 1;
    bit1.clear();
    bit2.clear();
}

void dfs1(int u, int p, bool keep) {
    int big = -1, best = -1;

    for (auto &e : adj[u]) {
        int v = e.to;
        if (v == p) continue;
        int s = subsz(v);
        if (s > best) {
            best = s;
            big = v;
        }
    }

    for (auto &e : adj[u]) {
        int v = e.to;
        if (v == p || v == big) continue;
        dfs1(v, u, false);
    }

    if (big != -1) dfs1(big, u, true);

    query(u, u);
    update(u);

    for (auto &e : adj[u]) {
        int v = e.to;
        if (v == p || v == big) continue;

        for (int t = tin[v]; t <= tout[v]; ++t)
            query(ord[t], u);

        for (int t = tin[v]; t <= tout[v]; ++t)
            update(ord[t]);
    }

    if (!keep) clear();
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    cin >> n;

    for (int i = 1; i < n; i++) {
        int x, y, z, t;
        cin >> x >> y >> z >> t;
        adj[x].push_back({y, z, t});
        adj[y].push_back({x, z, t});
    }

    P[1] = 1;
    dep[1] = 0;
    tim = 0;

    dfs(1, 0);

    sort(comp1.begin(), comp1.end());
    comp1.erase(unique(comp1.begin(), comp1.end()), comp1.end());

    sort(comp2.begin(), comp2.end());
    comp2.erase(unique(comp2.begin(), comp2.end()), comp2.end());

    bit1.init((int)comp1.size());
    bit2.init((int)comp2.size());

    dfs1(1, 0, false);
    cout << ans * inv(lhs) % mod * inv(rhs) % mod;
}