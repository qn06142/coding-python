struct segment_tree {
    int n;
    vector<long long> tree, lazy;

    segment_tree(int n) : n(n), tree(4 * n, -10000000000000000LL), lazy(4 * n, 0) {}

    void push(int u) {
        if (lazy[u] != 0) {
            tree[2 * u] += lazy[u];
            lazy[2 * u] += lazy[u];
            tree[2 * u + 1] += lazy[u];
            lazy[2 * u + 1] += lazy[u];
            lazy[u] = 0;
        }
    }

    void set_val(int u, int l, int r, int pos, long long val) {
        if (l == r) {
            tree[u] = val;
            lazy[u] = 0;
            return;
        }

        push(u);

        int mid = (l + r) / 2;

        if (pos <= mid) {
            set_val(2 * u, l, mid, pos, val);
        } else {
            set_val(2 * u + 1, mid + 1, r, pos, val);
        }

        tree[u] = max(tree[2 * u], tree[2 * u + 1]);
    }

    void update(int u, int l, int r, int ql, int qr, long long val) {
        if (ql <= l && r <= qr) {
            tree[u] += val;
            lazy[u] += val;
            return;
        }

        push(u);

        int mid = (l + r) / 2;

        if (ql <= mid) {
            update(2 * u, l, mid, ql, qr, val);
        }

        if (qr > mid) {
            update(2 * u + 1, mid + 1, r, ql, qr, val);
        }

        tree[u] = max(tree[2 * u], tree[2 * u + 1]);
    }

    long long query(int u, int l, int r, int ql, int qr) {
        if (ql > r || qr < l) {
            return -10000000000000000LL;
        }

        if (ql <= l && r <= qr) {
            return tree[u];
        }

        push(u);

        int mid = (l + r) / 2;
        long long res = -10000000000000000LL;

        if (ql <= mid) {
            res = max(res, query(2 * u, l, mid, ql, qr));
        }

        if (qr > mid) {
            res = max(res, query(2 * u + 1, mid + 1, r, ql, qr));
        }

        return res;
    }
};

struct stack_item {
    int l, r;
    long long val;
};

void update_stack(vector<stack_item>& stk, int i, long long val, segment_tree& st) {
    int cur_l = i - 1;

    while (!stk.empty() && stk.back().val >= val) {
        st.update(1, 0, st.n - 1, stk.back().l, stk.back().r, val - stk.back().val);
        cur_l = stk.back().l;
        stk.pop_back();
    }

    stk.push_back({cur_l, i - 1, val});
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(0);

    int n, k;
    cin >> n >> k;

    vector<long long> a(n + 1), b(n + 1), c(n + 1);

    for (int i = 1; i <= n; i++) {
        cin >> a[i];
    }

    for (int i = 1; i <= n; i++) {
        cin >> b[i];
    }

    for (int i = 1; i <= n; i++) {
        cin >> c[i];
    }

    vector<long long> dp_old(n + 1, -10000000000000000LL);

    long long min_a = 10000000000000000LL;
    long long min_b = 10000000000000000LL;
    long long min_c = 10000000000000000LL;

    for (int i = 1; i <= n; i++) {
        min_a = min(min_a, a[i]);
        min_b = min(min_b, b[i]);
        min_c = min(min_c, c[i]);

        dp_old[i] = min_a + min_b + min_c;
    }

    debug(n, k, dp_old[n]);

    for (int j = 2; j <= k; j++) {
        vector<long long> dp_new(n + 1, -10000000000000000LL);
        segment_tree st(n);

        vector<stack_item> stk_a, stk_b, stk_c;

        for (int i = 1; i <= n; i++) {
            int p = i - 1;

            if (p >= j - 1 && dp_old[p] > -5000000000000000LL) {
                st.set_val(1, 0, n - 1, p, dp_old[p] + a[i] + b[i] + c[i]);
            } else {
                st.set_val(1, 0, n - 1, p, -10000000000000000LL);
            }

            update_stack(stk_a, i, a[i], st);
            update_stack(stk_b, i, b[i], st);
            update_stack(stk_c, i, c[i], st);

            if (i >= j) {
                dp_new[i] = st.query(1, 0, n - 1, j - 1, i - 1);
            }

            if (i <= 3 || i == n) {
                debug(j, i, dp_new[i]);
            }
        }

        dp_old = move(dp_new);
        debug(j, dp_old[n]);
    }

    debug(dp_old[n]);

    cout << dp_old[n] << '\n';
}