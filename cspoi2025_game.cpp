struct Op { int L, R; int X; };

struct Query {
    int idx;      
    long long target;    
    int id;       
};

struct BIT {
    int n;
    vector<long long> bit;
    BIT(int n=0){init(n);}
    void init(int n_){n=n_; bit.assign(n+2,0);}
    void add(int i, long long v){ for(; i<=n; i+=i&-i) bit[i]+=v; }
    long long sumPrefix(int i){ long long s=0; for(; i>0; i-=i&-i) s+=bit[i]; return s; }

    void range_add(int l,int r,long long v){ if(l>r) return; add(l,v); if(r+1<=n) add(r+1,-v); }

    long long point(int i){ return sumPrefix(i); }
};
struct BIT2 {
    int n;
    vector<int> bit;
    BIT2(int n=0){ init(n); }
    void init(int n_){ n=n_; bit.assign(n+2,0); }
    void add(int i, int v){ for(; i<=n; i+=i&-i) bit[i]+=v; }
    long long sumPrefix(int i){ long long s=0; for(; i>0; i-=i&-i) s+=bit[i]; return s; }
};
int main(){
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int N, M, K;
    if(!(cin >> N >> M >> K)) return 0;
    vector<long long> A(N+1);
    for(int i=1;i<=N;i++) cin >> A[i];
    vector<long long> lucky(K);
    for(int i=0;i<K;i++) cin >> lucky[i];
    vector<Op> ops(M+1);
    for(int i=1;i<=M;i++){
        cin >> ops[i].L >> ops[i].R >> ops[i].X;
    }

    vector<int> init(N+1, 0); 
    for(int i=1;i<=N;i++){
        for(int j=0;j<K;j++){
            if(A[i] == lucky[j]) { init[i] = 1; break; }
        }
    }

    struct Qitem { int idx; long long target; int qid; };
    vector<Qitem> Qs;
    Qs.reserve((size_t)N * K);
    for(int i=1;i<=N;i++){
        if(init[i]) continue; 
        for(int j=0;j<K;j++){
            long long delta = lucky[j] - A[i];
            if(delta < 0) continue;
            if(delta == 0){

                continue;
            }
            Qs.push_back({i, delta, (int)Qs.size()});
        }
    }

    int Q = (int)Qs.size();

    vector<int> lo(Q,1), hi(Q, M+1); 

    vector<int> pos(Q, M+1);

    BIT bit(N);

    bool changed = true;
    vector<vector<int>> bucket(M+2);
    while(true){
        bool any = false;
        for(int i=0;i<=M+1;i++) bucket[i].clear();
        for(int i=0;i<Q;i++){
            if(lo[i] < hi[i]) {
                any = true;
                int mid = (lo[i] + hi[i]) >> 1;
                bucket[mid].push_back(i);
            }
        }
        if(!any) break;

        bit.init(N);

        for(int m=1;m<=M;m++){

            bit.range_add(ops[m].L, ops[m].R, ops[m].X);

            for(int qi : bucket[m]){

                long long cur = bit.point(Qs[qi].idx);
                if(cur >= Qs[qi].target){
                    hi[qi] = m;
                } else {
                    lo[qi] = m+1;
                }
            }
        }

    }
    for(int i=0;i<Q;i++) pos[i] = lo[i]; 

    vector<vector<int>> byPos(M+2);
    for(int i=0;i<Q;i++){
        if(pos[i] <= M) byPos[pos[i]].push_back(i);
    }

    bit.init(N);
    vector<char> good(Q, 0);
    for(int m=1;m<=M;m++){
        bit.range_add(ops[m].L, ops[m].R, ops[m].X);
        for(int qi : byPos[m]){
            long long cur = bit.point(Qs[qi].idx);
            if(cur == Qs[qi].target) good[qi] = 1;
        }
    }

    const int maxp = M+1;
    vector<int> earliest(N+1, maxp);

    for(int i=1;i<=N;i++){
        if(init[i]) earliest[i] = 0;
    }

    for(int qid=0;qid<Q;qid++){
        if(!good[qid]) continue;
        int idx = Qs[qid].idx;
        int p = pos[qid];
        if(p < earliest[idx]) earliest[idx] = p;
    }

    vector<int> T(N+1, M); 
    for(int i=1;i<=N;i++){
        if(earliest[i] == 0) T[i] = 0;
        else if(earliest[i] == maxp) T[i] = M; 
        else T[i] = earliest[i];
    }

    vector<vector<int>> bucketT(M+2);
    for(int i=1;i<=N;i++){
        if(T[i] >= 1 && T[i] <= M) bucketT[T[i]].push_back(i);
        else if(T[i] == M) bucketT[M].push_back(i);
    }



    BIT2 bit2(N);
    vector<long long> addAt(M+1,0);
    for(int j=M;j>=1;j--){

        for(int idx : bucketT[j]) {
            bit2.add(idx, 1); 
        }
        int L = ops[j].L, R = ops[j].R;
        long long cnt = bit2.sumPrefix(R) - bit2.sumPrefix(L-1);
        addAt[j] = cnt * 1LL * ops[j].X;
    }

    long long ans = 0;
    for(int i=1;i<=N;i++) ans += A[i];
    vector<long long> pref(M+1,0);
    for(int i=1;i<=M;i++) pref[i] = pref[i-1] + addAt[i];
    for(int i=1;i<=M;i++){
        cout << (ans + pref[i]) << '\n';
    }
}