    ios_base::sync_with_stdio(false);
    cin.tie(0);
    cin >> n >> q;
    for (int i = 0; i < n - 1; i++) {
        int u, v;
        cin >> u >> v;
        adj[u].push_back(v);
        adj[v].push_back(u);
    }
    
    dfs(1, 0, 0);
    for (int i = 1; i <= n; i++) {
        st[0][i] = rev[i];
    }
    for (int j = 1; (1 << j) <= n; j++) {
        for (int i = 1; i + (1 << j) - 1 <= n; i++) {
            int u = st[j - 1][i];
            int v = st[j - 1][i + (1 << (j - 1))];
            st[j][i] = (dep[u] < dep[v]) ? u : v;
        }
    }
    build(1, 1, n);
    
    while (q--) {
        int x, k;
        cin >> x >> k;
        vector<int> a(k);
        int lba = 0;
        
        for (int i = 0; i < k; i++) {
            cin >> a[i];
            if (check(a[i], x)) {
                if (lba == 0 || dep[a[i]] > dep[lba]) {
                    lba = a[i];
                }
            }
        }
        int l_ = 1, r_ = n;
        if (lba != 0) {
            int c = gc(x, lba);
            l_ = in[c];
            r_ = out[c];
        }
        vector<pair<int, int>> blocked;
        for (int a_ : a) {
            if (in[a_] >= l_ && out[a_] <= r_) {
                blocked.push_back({in[a_], out[a_]});
            }
        }
        sort(blocked.begin(), blocked.end());
        
        vector<pair<int, int>> merged;
        for (auto &intv : blocked) {
            if (merged.empty() || intv.first > merged.back().second) {
                merged.push_back(intv);
            }
        }
        
        vector<pair<int, int>> stor1;
        int curr = l_;
        for (auto &b : merged) {
            if (b.first > curr) {
                stor1.push_back({curr, b.first - 1});
            }
            curr = b.second + 1;
        }
        if (curr <= r_) {
            stor1.push_back({curr, r_});
        }
        
        stor ans = {0, 0};
        for (auto &gap : stor1) {
            ans = merge(ans, query(1, 1, n, gap.first, gap.second));
        }
        
        cout << max(dist(x, ans.u), dist(x, ans.v)) << "\n";
    }
