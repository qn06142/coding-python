const int maxn = 2e5 + 5;

int n, q;
vector<int> adj[maxn];
int in[maxn], out[maxn], dep[maxn], parent[maxn], timer;
int rev[maxn];
int up[20][maxn];
int st[20][maxn];
void dfs(int u, int p, int d) {
    parent[u] = p;
    dep[u] = d;
    in[u] = ++timer;
    rev[timer] = u;
    
    up[0][u] = p;
    for (int i = 1; i < 20; i++) {
        up[i][u] = up[i - 1][up[i - 1][u]];
    }
    
    for (int v : adj[u]) {
        if (v != p) {
            dfs(v, u, d + 1);
        }
    }
    out[u] = timer;
}

bool check(int u, int v) {
    return in[u] <= in[v] && out[u] >= out[v];
}

int lca(int u, int v) {
    if (u == v) return u;
    if (in[u] > in[v]) swap(u, v);
    if (check(u, v)) return u;
    int l = in[u] + 1, r = in[v];
    int k = 31 - __builtin_clz(r - l + 1);
    return parent[(dep[st[k][l]] < dep[st[k][r - (1 << k) + 1]]) ? st[k][l] : st[k][r - (1 << k) + 1]];
}

int dist(int u, int v) {
    if (u == 0 || v == 0) return -1;
    return dep[u] + dep[v] - 2 * dep[lca(u, v)];
}

int gc(int x, int lba) {
    for (int i = 20 - 1; i >= 0; i--) {
        if (dep[up[i][x]] > dep[lba]) {
            x = up[i][x];
        }
    }
    return x;
}
struct stor {
    int u, v;
};

stor merge(stor a_, stor b) {
    if (a_.u == 0) return b;
    if (b.u == 0) return a_;
    
    int nodes[4] = {a_.u, a_.v, b.u, b.v};
    int max_d = -1;
    stor best = {a_.u, a_.v};
    
    for (int i = 0; i < 4; i++) {
        for (int j = i + 1; j < 4; j++) {
            int d = dist(nodes[i], nodes[j]);
            if (d > max_d) {
                max_d = d;
                best = {nodes[i], nodes[j]};
            }
        }
    }
    return best;
}

stor tree[4 * maxn];

void build(int node, int tl, int tr) {
    if (tl == tr) {
        tree[node] = {rev[tl], rev[tl]};
        return;
    }
    int mid = (tl + tr) / 2;
    build(2 * node, tl, mid);
    build(2 * node + 1, mid + 1, tr);
    tree[node] = merge(tree[2 * node], tree[2 * node + 1]);
}

stor query(int node, int tl, int tr, int l, int r) {
    if (r < tl || tr < l) return {0, 0};
    if (l <= tl && tr <= r) return tree[node];
    int mid = (tl + tr) / 2;
    return merge(query(2 * node, tl, mid, l, r),
                      query(2 * node + 1, mid + 1, tr, l, r));
}

