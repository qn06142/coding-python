const int maxn = 2005;
const int mod = 1019972207;

int p[26][maxn], w[26][maxn], inv_w[26][maxn];
int val[26][maxn], way[26][maxn];
int ec[maxn][26], ew[maxn][26];
char a[26][maxn];

int add(int a, int b) {
    a += b;
    if (a >= mod) {
        a -= mod;
    }
    return a;
}

int mul(long long a, long long b) {
    return a * b % mod;
}

int pw(int a, int b) {
    int res = 1;
    while (b) {
        if (b & 1) {
            res = mul(res, a);
        }
        a = mul(a, a);
        b >>= 1;
    }
    return res;
}

int inv(int a) {
    return pw(a, mod - 2);
}

int main() {
    freopen("dangbep.inp", "r", stdin);
    freopen("dangbep.out", "w", stdout);
    ios_base::sync_with_stdio(false);
    cin.tie(0);

    int m, n, x, y;
    cin >> m >> n >> x >> y;

    debug(m, n, x, y);

    for (int r = 1; r <= m; r++) {
        string s;
        cin >> s;

        for (int i = 1; i <= n; i++) {
            a[r][i] = s[i - 1];
        }
    }

    int iv[26];
    for (int i = 1; i <= m; i++) {
        iv[i] = inv(i);
    }

    debug(iv);

    for (int c = 0; c < 26; c++) {
        w[c][0] = 1;
        inv_w[c][0] = 1;
    }

    for (int i = 1; i <= n; i++) {
        int cnt[26] = {};

        for (int r = 1; r <= m; r++) {
            cnt[a[r][i] - 'a']++;
        }

        for (int c = 0; c < 26; c++) {
            int co = cnt[c] == m ? 0 : m - 1 - cnt[c];
            int wa = cnt[c] == m ? 1 : m - cnt[c];

            p[c][i] = p[c][i - 1] + co;
            w[c][i] = mul(w[c][i - 1], wa);
            inv_w[c][i] = mul(inv_w[c][i - 1], iv[wa]);
        }

        if (i <= 3 || i == n) {
            debug(i, cnt);
        }
    }

    for (int c = 0; c < 26; c++) {
        way[c][0] = 1;
    }

    for (int i = 1; i <= n; i++) {
        int l = max(0, i - y);
        int r = i - x;

        debug(i, l, r);

        for (int c = 0; c < 26; c++) {
            if (l > r) {
                ec[i][c] = 1e9;
                ew[i][c] = 0;
                continue;
            }

            int mn = 1e9, sw = 0;

            for (int j = l; j <= r; j++) {
                if (val[c][j] < mn) {
                    mn = val[c][j];
                    sw = way[c][j];
                } else if (val[c][j] == mn) {
                    sw = add(sw, way[c][j]);
                }
            }

            if (mn >= (int)1e9 / 2) {
                ec[i][c] = 1e9;
                ew[i][c] = 0;
            } else {
                ec[i][c] = p[c][i] + mn;
                ew[i][c] = mul(w[c][i], sw);
            }
        }

        int mn1 = 1e9, mn2 = 1e9;
        int sw1 = 0, sw2 = 0;
        int bc = -1, cnt = 0;

        for (int c = 0; c < 26; c++) {
            if (ec[i][c] < mn1) {
                mn2 = mn1;
                sw2 = sw1;
                mn1 = ec[i][c];
                sw1 = ew[i][c];
                bc = c;
                cnt = 1;
            } else if (ec[i][c] == mn1) {
                sw1 = add(sw1, ew[i][c]);
                cnt++;
            } else if (ec[i][c] < mn2) {
                mn2 = ec[i][c];
                sw2 = ew[i][c];
            } else if (ec[i][c] == mn2) {
                sw2 = add(sw2, ew[i][c]);
            }
        }

        debug(i, mn1, mn2, sw1, sw2, bc, cnt);

        for (int c = 0; c < 26; c++) {
            int co, wa;

            if (cnt == 1) {
                if (c == bc) {
                    co = mn2;
                    wa = sw2;
                } else {
                    co = mn1;
                    wa = sw1;
                }
            } else {
                co = mn1;

                if (ec[i][c] == mn1) {
                    wa = (sw1 - ew[i][c] + mod) % mod;
                } else {
                    wa = sw1;
                }
            }

            if (co >= (int)1e9 / 2) {
                val[c][i] = 1e9;
                way[c][i] = 0;
            } else {
                val[c][i] = co - p[c][i];
                way[c][i] = mul(wa, inv_w[c][i]);
            }
        }

        if (i <= 5 || i == n) {
            debug(i, ec[i], ew[i]);
            debug(i, val[0][i], way[0][i]);
        }
    }

    int ans = 1e9, ways = 0;

    for (int c = 0; c < 26; c++) {
        if (ec[n][c] < ans) {
            ans = ec[n][c];
            ways = ew[n][c];
        } else if (ec[n][c] == ans) {
            ways = add(ways, ew[n][c]);
        }
    }

    debug(ans, ways);

    cout << ans << ' ' << ways << '\n';
}