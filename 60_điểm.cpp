int MOD;
static const int BUFSZ = 1<<20;
static char buf[BUFSZ];
static int buf_pos = 0, buf_len = 0;
inline int readChar() {
    if (buf_pos == buf_len) {
        buf_pos = 0;
        buf_len = fread(buf,1,BUFSZ,stdin);
        if (!buf_len) return EOF;
    }
    return buf[buf_pos++];
}
inline int readInt() {
    int c = readChar(), x = 0;
    while (c <= ' ') c = readChar();
    for (; c >= '0' && c <= '9'; c = readChar())
        x = x*10 + (c & 15);
    return x;
}
struct Matrix {
    int n, m;
    vector<vector<long long>> a;

    Matrix(int n = 0, int m = 0) : n(n), m(m), a(n, vector<long long>(m, 0)) {}

    Matrix(const vector<vector<long long>>& mat) {
        n = (int)mat.size();
        m = n ? (int)mat[0].size() : 0;
        a = mat;
    }
    static Matrix identity(int size) {
        Matrix I(size, size);
        for (int i = 0; i < size; i++) I.a[i][i] = 1;
        return I;
    }

    Matrix operator+(const Matrix& o) const {
        Matrix res(n, m);
        for (int i = 0; i < n; i++)
            for (int j = 0; j < m; j++)
                res.a[i][j] = (a[i][j] + o.a[i][j]) % MOD;
        return res;
    }

    Matrix operator-(const Matrix& o) const {
        Matrix res(n, m);
        for (int i = 0; i < n; i++)
            for (int j = 0; j < m; j++)
                res.a[i][j] = (a[i][j] - o.a[i][j] + MOD) % MOD;
        return res;
    }
    Matrix operator*(const Matrix& o) const {
        Matrix res(n, o.m);
        for (int i = 0; i < n; i++) {
            for (int k = 0; k < m; k++) {
                if (!a[i][k]) continue;
                for (int j = 0; j < o.m; j++) {
                    res.a[i][j] = (res.a[i][j] + a[i][k] * o.a[k][j]) % MOD;
                }
            }
        }
        return res;
    }
    Matrix power(long long exp) const {
        Matrix res = identity(n);
        Matrix base = *this;
        while (exp > 0) {
            if (exp & 1) res = res * base;
            base = base * base;
            exp >>= 1;
        }
        return res;
    }

    Matrix transpose() const {
        Matrix res(m, n);
        for (int i = 0; i < n; i++)
            for (int j = 0; j < m; j++)
                res.a[j][i] = a[i][j];
        return res;
    }
};
const int maxn = 2e6 + 5;
int a[maxn];
