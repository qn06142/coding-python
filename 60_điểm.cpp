const inline int enc(int i, int j, int m) {
    return (i - 1) * m + (j - 1);
}

long long binpow(long long base, long long exp) {
    base %= MOD;
    long long res = 1;
    while (exp > 0) {
        if (exp & 1) res = (res * base) % MOD;
        base = (base * base) % MOD;
        exp >>= 1;
    }
    return res;
}
