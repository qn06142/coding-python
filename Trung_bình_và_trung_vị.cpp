const int mod = 1019972207;
const int maxn = 200005;
const int maxk = 50;
const int maxsum = 25000;

int a[maxn];
long long fact[maxn], ifact[maxn];
int dp1[maxk][maxsum];
int dp2[maxk][maxsum];
int pref[maxsum];
long long pref0[maxn], pref1[maxn];

long long binpow(long long a, long long b) {
    long long r = 1;
    a %= mod;
    while (b) {
        if (b & 1) {
            r = r * a % mod;
        }
        a = a * a % mod;
        b >>= 1;
    }
    return r;
}
long long inv(long long x) {
    return binpow(x, mod - 2);
}
long long comb(int n, int k) {
    if (k < 0 or k > n) {
        return 0;
    }
    return fact[n] * ifact[k] % mod * ifact[n - k] % mod;
}
long long sub1(int n) {
    int c1 = 0, c2 = 0;
    for (int i = 1; i <= n; i++) {
        if (a[i] == 1) {
            c1++;
        } else if (a[i] == 2) {
            c2++;
        }
    }
    debug(c1, c2);
    if (!c1 or c2 <= 1) {
        return 0;
    }
    int mx = max(c1, c2);
    fact[0] = 1;
    ifact[0] = 1;
    for (int i = 1; i <= mx; i++) {
        fact[i] = fact[i - 1] * i % mod;
    }
    ifact[mx] = inv(fact[mx]);
    for (int i = mx - 1; i >= 0; i--) {
        ifact[i] = ifact[i + 1] * (i + 1) % mod;
    }
    for (int v = 0; v <= c2; v++) {
        int p = v % 2;
        if (!p) {
            pref0[v] = comb(c2, v);
            if (v >= 2) {
                pref0[v] = (pref0[v] + pref0[v - 2]) % mod;
            }
            if (v >= 1) {
                pref1[v] = pref1[v - 1];
            }
        } else {
            pref1[v] = comb(c2, v);
            if (v >= 2) {
                pref1[v] = (pref1[v] + pref1[v - 2]) % mod;
            }
            pref0[v] = pref0[v - 1];
        }
    }
    long long ans = 0;
    for (int u = 1; u <= c1; u++) {
        int p = u % 2 == 0;
        int l = u + 1;
        if (l > c2) {
            break;
        }
        long long s = p ? pref1[c2] : pref0[c2];
        if (l >= 2) {
            if (p) {
                s = (s - pref1[l - 2] + mod) % mod;
            } else {
                s = (s - pref0[l - 2] + mod) % mod;
            }
        }
        ans = (ans + comb(c1, u) * s) % mod;
    }
    debug(ans);
    return ans;
}
long long sub2(int n) {
    sort(a + 1, a + n + 1);
    long long ans = 0;
    int lim = 1 << n;
    for (int mask = 1; mask < lim; mask++) {
        int len = 0, sum = 0;
        for (int i = 1; i <= n; i++) {
            if (mask >> (i - 1) & 1) {
                len++;
                sum += a[i];
            }
        }
        if (!(len & 1)) {
            continue;
        }
        int target = len / 2, cur = 0, med = 0;
        for (int i = 1; i <= n; i++) {
            if (mask >> (i - 1) & 1) {
                if (cur == target) {
                    med = a[i];
                    break;
                }

                cur++;
            }
        }
        if (sum < len * med) {
            ans = (ans + 1) % mod;
        }
    }
    debug(n, ans);
    return ans;
}

void add(int dp[maxk][maxsum], int v) {
    for (int c = maxk; c >= 1; c--) {
        int mx = c * 500;

        for (int s = mx; s >= v; s--) {
            dp[c][s] += dp[c - 1][s - v];

            if (dp[c][s] >= mod) {
                dp[c][s] -= mod;
            }
        }
    }
}

void del(int dp[maxk][maxsum], int v) {
    for (int c = 1; c <= maxk; c++) {
        int mx = c * 500;

        for (int s = v; s <= mx; s++) {
            dp[c][s] -= dp[c - 1][s - v];

            if (dp[c][s] < 0) {
                dp[c][s] += mod;
            }
        }
    }
}

long long sub3(int n) {
    sort(a + 1, a + n + 1);
    dp2[0][0] = 1;
    for (int i = 1; i <= n; i++) {
        add(dp2, a[i]);
    }
    dp1[0][0] = 1;
    long long ans = 0;
    for (int m = 1; m <= n; m++) {
        int v = a[m];
        del(dp2, v);
        int mxk = min(m - 1, n - m);
        for (int k = 1; k <= mxk; k++) {
            int mxr = k * 500;
            pref[0] = dp2[k][0];
            for (int s = 1; s <= mxr; s++) {
                pref[s] = pref[s - 1] + dp2[k][s];

                if (pref[s] >= mod) {
                    pref[s] -= mod;
                }
            }
            int mxl = k * v;
            for (int sl = 0; sl <= mxl; sl++) {
                if (!dp1[k][sl]) {
                    continue;
                }
                int lim = 2 * k * v - sl - 1;
                if (lim < 0) {
                    continue;
                }
                int ways = lim >= mxr ? pref[mxr] : pref[lim];
                ans = (ans + 1LL * dp1[k][sl] * ways) % mod;
            }
        }
        add(dp1, v);
        if (m <= 3 or m == n) {
            debug(m, v, mxk, ans);
        }
    }
    debug(ans);
    return ans;
}
