__int128_t pw(__int128_t a, int b) {
    __int128_t r = 1;
    while (b--) r *= a;
    return r;
}

void solve1(long long n) {
    long long m = 1;

    while (m * (m + 1) / 2 < n ||
           (m * (m + 1) / 2 - n) % 2 != 0)
        m++;

    long long d = (m * (m + 1) / 2 - n) / 2;
    string s(m, '+');

    for (long long i = m; i >= 1; i--) {
        if (d >= i) {
            s[i - 1] = '-';
            d -= i;
        }
    }

    cout << m << ' ' << s << '\n';
}

void solve(int k, long long n) {
    __int128_t target = n, sum = 0;
    long long m = 1;

    while (sum < target ||
           (m * (m + 1) / 2) % 2 != target % 2) {
        m++;
        sum += pw(m, k);
    }

    int pad = 4 * (1 << min(k, 6));
    m += pad;

    while ((m * (m + 1) / 2) % 2 != target % 2)
        m++;

    vector<__int128_t> p(m + 1);

    for (int i = 1; i <= m; i++)
        p[i] = pw(i, k);

    string s(m, '+');
    __int128_t cur = 0;

    for (int i = m; i >= 1; i--) {
        if (cur + p[i] <= target) {
            cur += p[i];
        } else if (cur - p[i] >= target) {
            s[i - 1] = '-';
            cur -= p[i];
        } else {
            __int128_t x = cur + p[i] - target;
            __int128_t y = cur - p[i] - target;

            if (x < 0) x = -x;
            if (y < 0) y = -y;

            if (x <= y) {
                cur += p[i];
            } else {
                s[i - 1] = '-';
                cur -= p[i];
            }
        }
    }

    mt19937 rng(1337);
    int it = 15000000;
    __int128_t best = cur - target;

    if (best < 0)
        best = -best;

    while (it-- && best > 0) {
        int mx = min(m, 60LL);
        int i = 1 + rng() % mx;

        __int128_t nxt = cur;

        if (s[i - 1] == '+')
            nxt -= 2 * p[i];
        else
            nxt += 2 * p[i];

        __int128_t d = nxt - target;

        if (d < 0)
            d = -d;

        if (d < best) {
            best = d;
            cur = nxt;
            s[i - 1] = s[i - 1] == '+' ? '-' : '+';
        }
    }

    cout << m << ' ' << s << '\n';
}

