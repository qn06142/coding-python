const int maxn = 200005;
const int maxe = 3 * maxn + 5;

struct thing {
    priority_queue<int> pq, del;

    void push(int x) {
        pq.push(x);
    }

    void erase(int x) {
        del.push(x);
    }

    int top() {
        while (!pq.empty() && !del.empty() && pq.top() == del.top()) {
            pq.pop();
            del.pop();
        }

        return pq.empty() ? 0 : pq.top();
    }
} seg[4 * maxn];

struct op {
    int t;
    int xmin, xmax, ymin, ymax;
};
struct event {
    int x, type, id, yl, yr;
    bool operator<(const event& other) const {
        if (x != other.x) {
            return x < other.x;
        }
        return type < other.type;
    }
};

op ops[maxn];
pair<int, int> queries[maxn];
int ys[maxn], ansop[maxn];
event events[maxe];
char res[maxn];

void update(int u, int l, int r, int ql, int qr, int val, int type) {
    if (ql <= l && r <= qr) {
        if (type == 1) {
            seg[u].push(val);
        } else {
            seg[u].erase(val);
        }

        return;
    }

    int mid = (l + r) / 2;

    if (ql <= mid) {
        update(2 * u, l, mid, ql, qr, val, type);
    }

    if (qr > mid) {
        update(2 * u + 1, mid + 1, r, ql, qr, val, type);
    }
}

int query(int u, int l, int r, int pos) {
    int ans = seg[u].top();
    if (l == r) {
        return ans;
    }
    int mid = (l + r) / 2;
    if (pos <= mid) {
        ans = max(ans, query(2 * u, l, mid, pos));
    } else {
        ans = max(ans, query(2 * u + 1, mid + 1, r, pos));
    }
    return ans;
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(0);

    int m, n, p, q;
    cin >> m >> n >> p >> q;

    for (int i = 1; i <= p; i++) {
        int t, x1, y1, x2, y2;
        cin >> t >> x1 >> y1 >> x2 >> y2;

        ops[i] = {
            t,
            min(x1, x2),
            max(x1, x2),
            min(y1, y2),
            max(y1, y2)
        };
    }

    for (int i = 1; i <= q; i++) {
        cin >> queries[i].first >> queries[i].second;
        ys[i] = queries[i].second;
    }

    sort(ys + 1, ys + q + 1);
    int ny = unique(ys + 1, ys + q + 1) - ys - 1;

    int ecnt = 0;

    for (int i = 1; i <= p; i++) {
        int l = lower_bound(ys + 1, ys + ny + 1, ops[i].ymin) - ys;
        int r = upper_bound(ys + 1, ys + ny + 1, ops[i].ymax) - ys - 1;

        if (l <= r) {
            events[++ecnt] = {ops[i].xmin, 1, i, l, r};
            events[++ecnt] = {ops[i].xmax, 3, i, l, r};
        }
    }

    for (int i = 1; i <= q; i++) {
        int pos = lower_bound(ys + 1, ys + ny + 1, queries[i].second) - ys;
        events[++ecnt] = {queries[i].first, 2, i, pos, pos};
    }

    sort(events + 1, events + ecnt + 1);

    debug(m, n, p, q);
    debug(ny, ecnt);

    for (int i = 1; i <= ecnt; i++) {
        event e = events[i];

        if (e.type == 1) {
            update(1, 1, ny, e.yl, e.yr, e.id, 1);
        } else if (e.type == 3) {
            update(1, 1, ny, e.yl, e.yr, e.id, 3);
        } else {
            ansop[e.id] = query(1, 1, ny, e.yl);
        }
    }

    for (int i = 1; i <= q; i++) {
        int id = ansop[i];

        if (id == 0) {
            res[i] = 'W';
            continue;
        }

        op cur = ops[id];

        int rp = queries[i].first - cur.xmin + 1;
        int cp = queries[i].second - cur.ymin + 1;

        if (cur.t == 1) {
            int rem = (rp - 1) % 3;

            if (rem == 0) {
                res[i] = 'B';
            } else if (rem == 1) {
                res[i] = 'R';
            } else {
                res[i] = 'Y';
            }
        } else if (cur.t == 2) {
            int rem = (cp - 1) % 3;

            if (rem == 0) {
                res[i] = 'B';
            } else if (rem == 1) {
                res[i] = 'Y';
            } else {
                res[i] = 'R';
            }
        } else {
            int rem = ((cp - rp) % 3 + 3) % 3;

            if (rem == 0) {
                res[i] = 'B';
            } else if (rem == 1) {
                res[i] = 'Y';
            } else {
                res[i] = 'R';
            }
        }

        if (i <= 3 || i == q) {
            debug(i, id, res[i]);
        }
    }
    for(int i = 1; i <= q; i++) {
        cout << res[i];
    }

    debug(ecnt, ny);
}