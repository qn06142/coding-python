const int maxn = 1e5 + 5;
vector<pair<int, int>> adj[maxn];
long long m;
long long modp(long long a, long long b) {
    long long ans = 1;
    a %= m;
    while (b > 0) {
        if (b & 1) ans = (ans * a) % m;
        a = (a * a) % m;
        b >>= 1;
    }
    return ans;
}
long long extgcd(long long a, long long b, long long &x, long long &y) {
    if (b == 0) { x = 1; y = 0; return a; }
    long long x1, y1;
    long long g = extgcd(b, a % b, x1, y1);
    x = y1;
    y = x1 - y1 * (a / b);
    return g;
}

long long inver(long long a, long long mod) {
    long long x, y;
    extgcd(a, mod, x, y);
    return (x % mod + mod) % mod;
}

long long pow10[2 * maxn];
long long inv10[2 * maxn];

long long s[maxn];
long long e[maxn];
long long k1[maxn];
long long k2[maxn];
long long d[maxn];

void dfs1(int u = 1, int v = 0, int dp = 0) {
    if (v == 0) {
        d[u] = 0;
        s[u] = 0;
        e[u] = 0;
    } else {
        d[u] = d[v] + 1;
        s[u] = (dp * pow10[d[v]] + s[v]) % m;
        e[u] = (e[v] * 10 + dp) % m;
    }

    k1[u] = s[u];
    k2[u] = (e[u] * inv10[d[u]]) % m;

    for (auto [i, w] : adj[u]) {
        if (i != v) {
            dfs1(i, u, w);
        }
    }
}
int sz[maxn];
int heavy[maxn];

void dfs2(int u = 1, int v = 0) {
    sz[u] = 1;
    heavy[u] = 0;
    int max_sz = 0;
    for (auto [i, w] : adj[u]) {
        if (i != v) {
            dfs2(i, u);
            sz[u] += sz[i];
            if (sz[i] > max_sz) {
                max_sz = sz[i];
                heavy[u] = i;
            }
        }
    }
}

void get_nodes(int u, int v, vector<int>& nodes) {
    nodes.push_back(u);
    for (auto [i, w] : adj[u]) {
        if (i != v) {
            get_nodes(i, u, nodes);
        }
    }
}

map<long long, int> cs;
map<long long, int> ce;
long long ans = 0;

void dfs3(int u = 1, int v = 0, bool keep = false) {
    for (auto [i, w] : adj[u]) {
        if (i != v && i != heavy[u]) {
            dfs3(i, u, false);
        }
    }
    if (heavy[u] != 0) {
        dfs3(heavy[u], u, true);
    }
    if (ce.count(k2[u])) {
        ans += ce[k2[u]];
    }
    if (cs.count(s[u])) {
        ans += cs[s[u]]; 
    }
    cs[s[u]]++;
    ce[k2[u]]++;
    for (auto [i, w] : adj[u]) {
        if (i != v && i != heavy[u]) {
            vector<int> hist;
            get_nodes(i, u, hist);
            for (int x : hist) {
                auto it_k1 = cs.find((s[u] + pow10[2 * d[u]] * ((k2[u] - k2[x] + m) % m)) % m);
                if (it_k1 != cs.end()) ans += it_k1->second;
                auto it_k2 = ce.find((k2[u] + ((s[u] - s[x] + m) % m) * inv10[2 * d[u]]) % m);
                if (it_k2 != ce.end()) ans += it_k2->second;
            }
            for (int x : hist) {
                cs[s[x]]++;
                ce[k2[x]]++;
            }
        }
    }
    if (!keep) {
        vector<int> hist;
        get_nodes(u, v, hist);
        for (int x : hist) {
            cs[s[x]]--;
            if (cs[s[x]] == 0) cs.erase(s[x]);

            ce[k2[x]]--;
            if (ce[k2[x]] == 0) ce.erase(k2[x]);
        }
    }
}

