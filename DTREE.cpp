int main(){
    int n,q;
    cin >> n >> q;
    vector<vector<int>> adj(n+1);
    for(int i=0;i<n-1;i++){
        int a,b; cin>>a>>b;
        adj[a].push_back(b);
        adj[b].push_back(a);
    }
    vector<int> qs(q+1);
    for(int i=1;i<=q;i++) cin>>qs[i];

    int lg=1;
    while((1<<lg)<=n) lg++;
    vector<vector<int>> up(lg, vector<int>(n+1));
    vector<int> dep(n+1, -1);

    int root=1;
    queue<int> qu;
    dep[root]=0; up[0][root]=root; qu.push(root);
    while(!qu.empty()){
        int u=qu.front(); qu.pop();
        for(int v: adj[u]) if(dep[v]==-1){
            dep[v]=dep[u]+1;
            up[0][v]=u;
            qu.push(v);
        }
    }
    for(int k=1;k<lg;k++) for(int i=1;i<=n;i++) up[k][i]=up[k-1][ up[k-1][i] ];

    auto lca = [&](int a,int b){
        if(dep[a]<dep[b]) swap(a,b);
        int d = dep[a]-dep[b];
        for(int k=0;k<lg;k++) if(d&(1<<k)) a=up[k][a];
        if(a==b) return a;
        for(int k=lg-1;k>=0;k--) if(up[k][a]!=up[k][b]){
            a=up[k][a]; b=up[k][b];
        }
        return up[0][a];
    };
    function<int(int,int)> dist = [&](int a,int b){
        int c=lca(a,b);
        return dep[a]+dep[b]-2*dep[c];
    };

    struct dsu {
        vector<int> p,sz,e1,e2,dm;
        dsu(int n=0){ init(n); }
        void init(int n){
            p.assign(n+1,-1);
            sz.assign(n+1,0);
            e1.assign(n+1,-1);
            e2.assign(n+1,-1);
            dm.assign(n+1,0);
        }
        void mk(int x){ p[x]=x; sz[x]=1; e1[x]=e2[x]=x; dm[x]=0; }
        int findp(int x){ return p[x]==x ? x : p[x]=findp(p[x]); }
        void merge_into(int a,int b, function<int(int,int)>& df){
            p[b]=a;
            sz[a]+=sz[b];
            int best = dm[a];
            pair<int,int> bp = {e1[a], e2[a]};
            if(dm[b]>best){ best=dm[b]; bp={e1[b], e2[b]}; }
            int A[2] = {e1[a], e2[a]};
            int B[2] = {e1[b], e2[b]};
            for(int i=0;i<2;i++) for(int j=0;j<2;j++){
                int d = df(A[i], B[j]);
                if(d>best){ best=d; bp={A[i], B[j]}; }
            }
            e1[a]=bp.first; e2[a]=bp.second; dm[a]=best;
        }
    };

    auto unite = [&](dsu &D, int x, int y, function<int(int,int)>& df){
        int rx = D.findp(x), ry = D.findp(y);
        if(rx==ry) return rx;
        if(D.sz[rx] < D.sz[ry]) swap(rx, ry);
        D.merge_into(rx, ry, df);
        return rx;
    };

    vector<char> rem(n+1,0);
    for(int i=1;i<=q;i++) rem[qs[i]]=1;

    dsu A(n), B(n);
    A.init(n); B.init(n);
    vector<char> acta(n+1,0), actb(n+1,0);

    int gau=-1,gav=-1,gad=0;
    int gbu=-1,gbv=-1,gbd=0;

    auto upd1 = [&](int &u,int &v,int &d,int x){
        if(u==-1){ u=v=x; d=0; return; }
        int d1 = dist(x,u);
        if(d1> d){ v=x; d=d1; return; }
        int d2 = dist(x,v);
        if(d2> d){ u=x; d=d2; return; }
    };
    auto upd2 = [&](int &u,int &v,int &d,int a,int b){
        if(a<1||b<1) return;
        int dd = dist(a,b);
        if(u==-1 || dd> d){ u=a; v=b; d=dd; }
    };

    for(int i=1;i<=n;i++){
        if(!rem[i]){
            acta[i]=1;
            A.mk(i);
            for(int nb: adj[i]) if(acta[nb]) unite(A,i,nb,dist);
            upd1(gau,gav,gad,i);
        }
    }
    for(int i=1;i<=n;i++) if(acta[i] && A.findp(i)==i) upd2(gau,gav,gad,A.e1[i], A.e2[i]);

    vector<int> rea(q+1);
    rea[0] = (gau==-1 ? 0 : gad);

    for(int k=1;k<=q;k++){
        int node = qs[q-k+1];
        acta[node]=1;
        A.mk(node);
        upd1(gau,gav,gad,node);
        for(int nb: adj[node]){
            if(!acta[nb]) continue;
            int r1 = A.findp(node), r2 = A.findp(nb);
            if(r1==r2) continue;
            int a1=A.e1[r1], a2=A.e2[r1], b1=A.e1[r2], b2=A.e2[r2];
            upd2(gau,gav,gad,a1,b1);
            upd2(gau,gav,gad,a1,b2);
            upd2(gau,gav,gad,a2,b1);
            upd2(gau,gav,gad,a2,b2);
            upd2(gau,gav,gad,node,b1);
            upd2(gau,gav,gad,node,b2);
            int root = unite(A, node, nb, dist);
            upd2(gau,gav,gad,A.e1[root], A.e2[root]);
        }
        rea[k]=gad;
    }

    vector<int> reb(q+1);
    for(int i=1;i<=q;i++){
        int node = qs[i];
        actb[node]=1;
        B.mk(node);
        upd1(gbu,gbv,gbd,node);
        for(int nb: adj[node]){
            if(!actb[nb]) continue;
            int r1=B.findp(node), r2=B.findp(nb);
            if(r1==r2) continue;
            int a1=B.e1[r1], a2=B.e2[r1], b1=B.e1[r2], b2=B.e2[r2];
            upd2(gbu,gbv,gbd,a1,b1);
            upd2(gbu,gbv,gbd,a1,b2);
            upd2(gbu,gbv,gbd,a2,b1);
            upd2(gbu,gbv,gbd,a2,b2);
            upd2(gbu,gbv,gbd,node,b1);
            upd2(gbu,gbv,gbd,node,b2);
            int root = unite(B, node, nb, dist);
            upd2(gbu,gbv,gbd,B.e1[root], B.e2[root]);
        }
        reb[i]=gbd;
    }

    for(int i=1;i<=q;i++){
        cout << rea[q-i] << " " << reb[i] << '\n';
    }
    return 0;
}