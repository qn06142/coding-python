#include <bits/stdc++.h>
using namespace std;

const int maxn = 1e5 + 5;
int a[maxn], spf[maxn], cnt[maxn];
int n;
long long ans = 0;

void sieve() {
    for(int i = 2; i < maxn; i++) {
        if(!spf[i]) {
            for(int j = i; j < maxn; j += i) {
                if(!spf[j]) spf[j] = i;
            }
        }
    }
}

void add(int x, int delta) {
    int p[10], k = 0;
    while(x > 1) {
        int d = spf[x];
        p[k++] = d;
        while(x % d == 0) x /= d;
    }
    for(int mask = 1; mask < (1 << k); mask++) {
        int d = 1;
        for(int i = 0; i < k; i++) {
            if(mask >> i & 1) d *= p[i];
        }
        cnt[d] += delta;
    }
    cnt[1] += delta;
}

int query(int x) {
    int p[10], k = 0;
    while(x > 1) {
        int d = spf[x];
        p[k++] = d;
        while(x % d == 0) x /= d;
    }
    int res = cnt[1];
    for(int mask = 1; mask < (1 << k); mask++) {
        int d = 1;
        for(int i = 0; i < k; i++) {
            if(mask >> i & 1) d *= p[i];
        }
        if(__builtin_popcount((unsigned)mask) & 1) res -= cnt[d];
        else res += cnt[d];
    }
    return res;
}

void recur(int l, int r) {
    if(l == r) {
        ans += (a[l] == 1);
        return;
    }

    int mid = (l + r) / 2;
    recur(l, mid);
    recur(mid + 1, r);

    int nl = mid - l + 1, nr = r - mid;
    vector<int> sufmi(nl), sufma(nl);
    vector<int> prefmi(nr), prefma(nr);

    sufmi[0] = sufma[0] = a[mid];
    for(int i = 1; i < nl; i++) {
        sufma[i] = max(sufma[i - 1], a[mid - i]);
        sufmi[i] = min(sufmi[i - 1], a[mid - i]);
    }

    prefmi[0] = prefma[0] = a[mid + 1];
    for(int i = 1; i < nr; i++) {
        prefma[i] = max(prefma[i - 1], a[mid + 1 + i]);
        prefmi[i] = min(prefmi[i - 1], a[mid + 1 + i]);
    }
    debug(l, r);
    int pmax = 0, pmin = 0;
    for(int i = 0; i < nl; i++) {
        while(pmax < nr && prefma[pmax] <= sufma[i]) pmax++;
        while(pmin < nr && prefmi[pmin] >= sufmi[i]) pmin++;
        if(gcd(sufma[i], sufmi[i]) == 1) {
            debug(pmax, pmin);
            ans += min(pmax, pmin);
        }
    }

    debug(l, r);
    pmax = pmin = 0;
    for(int i = 0; i < nr; i++) {
        while(pmax < nl && sufma[pmax] < prefma[i]) pmax++;
        while(pmin < nl && sufmi[pmin] > prefmi[i]) pmin++;
        if(gcd(prefma[i], prefmi[i]) == 1) {
            debug(pmax, pmin);
            ans += min(pmax, pmin);
        }
    }

    pmax = pmin = 0;
    for(int i = 0; i < nl; i++) {
        while(pmax < nr && prefma[pmax] <= sufma[i]) {
            add(prefmi[pmax], 1);
            pmax++;
        }
        while(pmin < pmax && prefmi[pmin] >= sufmi[i]) {
            add(prefmi[pmin], -1);
            pmin++;
        }
        ans += query(sufma[i]);
    }

    while(pmin < pmax) {
        add(prefmi[pmin], -1);
        pmin++;
    }

    pmax = pmin = 0;
    for(int i = 0; i < nr; i++) {
        while(pmax < nl && sufma[pmax] < prefma[i]) {
            add(sufmi[pmax], 1);
            pmax++;
        }
        while(pmin < pmax && sufmi[pmin] > prefmi[i]) {
            add(sufmi[pmin], -1);
            pmin++;
        }
        ans += query(prefma[i]);
    }

    while(pmin < pmax) {
        add(sufmi[pmin], -1);
        pmin++;
    }
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(0);

    sieve();

    cin >> n;
    for(int i = 1; i <= n; i++) {
        cin >> a[i];
    }

    recur(1, n);

    cout << ans << '\n';
}