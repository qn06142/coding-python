const long long INF = 1e18;

struct Edge {
    int v;
    long long w;
};

struct State {
    long long w;
    long long cnt;

    bool operator<(const State &o) const {
        if (w != o.w) return w < o.w;
        return cnt < o.cnt;
    }

    State operator+(const State &o) const {
        return {w + o.w, cnt + o.cnt};
    }
};

int n, q;
vector<vector<Edge>> g;
vector<int> order;
vector<int> par;
vector<State> dp0, dp1;

void precompute() {
    par.assign(n + 1, 0);
    vector<bool> vis(n + 1, false);
    queue<int> q;

    q.push(1);
    vis[1] = true;
    vector<int> ord;
    ord.reserve(n);

    while (!q.empty()) {
        int u = q.front();
        q.pop();
        ord.push_back(u);

        for (const auto &e : g[u]) {
            if (!vis[e.v]) {
                vis[e.v] = true;
                par[e.v] = u;
                q.push(e.v);
            }
        }
    }

    order = ord;
    reverse(order.begin(), order.end());
}

State recur(long long lam, bool unit = false) {
    for (int u : order) {
        State sum = {0, 0};
        State ans = {-INF, -INF};

        for (const auto &e : g[u]) {
            if (e.v == par[u]) continue;

            State max_v = max(dp0[e.v], dp1[e.v]);
            sum = sum + max_v;

            long long weight = unit ? 1 : e.w;
            State match_v = dp0[e.v] + State{weight - lam, 1};
            State delta = {match_v.w - max_v.w, match_v.cnt - max_v.cnt};

            if (ans < delta) {
                ans = delta;
            }
        }

        dp0[u] = sum;
        if (ans.w <= -INF / 2) {
            dp1[u] = {-INF, -INF};
        } else {
            dp1[u] = sum + ans;
        }
    }

    return max(dp0[1], dp1[1]);
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);

    cin >> n >> q;

    g.resize(n + 1);
    for (int i = 1; i < n; i++) {
        int u, v;
        long long w;
        cin >> u >> v >> w;
        g[u].push_back({v, w});
        g[v].push_back({u, w});
    }

    precompute();

    dp0.resize(n + 1);
    dp1.resize(n + 1);
    int kmax = recur(0, true).cnt;

    while (q--) {
        int k;
        cin >> k;

        if (k <= 0 || k > kmax) {
            cout << 0 << '\n';
            continue;
        }
        long long lo = -1e12, hi = 1e12;
        long long lam = 0;

        while (lo <= hi) {
            long long mid = lo + (hi - lo) / 2;
            State res = recur(mid);

            if (res.cnt >= k) {
                lam = mid;
                lo = mid + 1;
            } else {
                hi = mid - 1;
            }
        }

        State res = recur(lam);
        cout << res.w + 1LL * k * lam << '\n';
    }
}